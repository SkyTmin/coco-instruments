def put_face(m, x, y, c):
    """Настенное (лампа, часы, плакат): стена, под ней пол."""
    assert m.g[y][x] in '#WQJFAVUHnvu', ('not wall', x, y, c, m.g[y][x])
    assert m.g[y + 1][x] in WALK, ('no floor below', x, y, c, m.g[y + 1][x])
    m.put(x, y, c)


def faces(m, y, x0, x1, c, only='#'):
    """Все клетки стены в ряду `y`, под которыми пол, — буквой `c`."""
    for x in range(max(1, x0), min(W - 2, x1) + 1):
        if m.g[y][x] in only and m.g[y + 1][x] in WALK and not m.lock[y][x]:
            m.g[y][x] = c


def fill(m, x0, y0, x1, y1, c):
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            if m.inb(x, y):
                m.g[y][x] = c


def paint(m, x0, y0, x1, y1, ch, share=1.0, ok='t.'):
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            if 0 <= y < m.h and 0 < x < W - 1 and m.g[y][x] in ok and not m.lock[y][x]:
                if m.rng.random() < share:
                    m.g[y][x] = ch


def speckle(m, x0, y0, x1, y1, ch, n, ok='t', gap=2):
    cells = [(x, y) for y in range(y0, y1 + 1) for x in range(x0, x1 + 1)
             if 0 <= y < m.h and 0 < x < W - 1 and m.g[y][x] in ok and not m.lock[y][x]]
    m.rng.shuffle(cells)
    placed = []
    for (x, y) in cells:
        if len(placed) >= n:
            break
        if any(abs(x - a) + abs(y - b) < gap for a, b in placed):
            continue
        m.g[y][x] = ch
        placed.append((x, y))
    return placed


def hole(m, x, y):
    """Нора (вентрешётка, дыра в плитке): стена, рядом пол."""
    def ok(x, y):
        return (m.get(x, y) in '#WJ' and not m.lock[y][x] and 1 < x < W - 2 and any(
            m.get(x + dx, y + dy) in FLOORS for dx, dy in ((0, 1), (1, 0), (-1, 0), (0, -1))))
    if ok(x, y):
        m.put(x, y, 'o')
        return
    for r in range(1, 6):
        for dx, dy in ((-r, 0), (r, 0), (0, -r), (0, r)):
            if ok(x + dx, y + dy):
                print(f'  сдвиг o ({x},{y}) -> ({x+dx},{y+dy})', file=sys.stderr)
                m.put(x + dx, y + dy, 'o')
                return
    raise AssertionError(('no burrow spot', x, y))


def track(m, y, x0, x1, deep=((1, 3), (60, 62))):
    """Путь: два ряда рельсов в столбцах x0…x1 (по ним ходят), а в
    диапазонах `deep` — тоннель в темноту: туда не пройти, оттуда выходит
    поезд."""
    for x in range(x0, x1 + 1):
        m.g[y][x] = '='
        m.g[y + 1][x] = '-'
    for (a, b) in deep:
        for x in range(a, b + 1):
            m.g[y][x] = ')'
            m.g[y + 1][x] = '_'
            m.lock[y][x] = m.lock[y + 1][x] = True


def portals(m):
    """Стена над тоннелем в темноту — свод портала (своё лицо)."""
    for y in range(1, m.h):
        for x in range(1, W - 1):
            if m.g[y][x] == ')' and m.g[y - 1][x] in '#WJn':
                m.g[y - 1][x] = 'V'
                m.lock[y - 1][x] = True


def crossing(m, y, x0, x1):
    for x in range(x0, x1 + 1):
        m.g[y][x] = 'h'
        m.g[y + 1][x] = 'j'


def floor_at(m, x, y, c, ok='t.,msedyqzkrwe'):
    """Предмет на пол: рядом, если клетка занята."""
    if m.g[y][x] in ok and not m.lock[y][x]:
        m.put(x, y, c)
        return (x, y)
    for r in (1, 2, 3):
        for dy in range(-r, r + 1):
            for dx in range(-r, r + 1):
                if m.get(x + dx, y + dy) in ok and not m.lock[y + dy][x + dx]:
                    print(f'  сдвиг {c} ({x},{y}) -> ({x+dx},{y+dy})', file=sys.stderr)
                    m.put(x + dx, y + dy, c)
                    return (x + dx, y + dy)
    raise AssertionError(('no floor near', x, y, c))


def wall_at(m, x, y, c):
    """Настенное рядом: ищем стену с полом под ней."""
    def ok(x, y):
        return (m.get(x, y) in '#WJFAQn' and not m.lock[y][x] and 0 < y < m.h - 1
                and m.get(x, y + 1) in WALK)
    if ok(x, y):
        m.put(x, y, c)
        return
    for r in (1, 2, 3):
        for dy in (0, -1, 1):
            for dx in range(-r, r + 1):
                if ok(x + dx, y + dy):
                    print(f'  сдвиг {c} ({x},{y}) -> ({x+dx},{y+dy})', file=sys.stderr)
                    m.put(x + dx, y + dy, c)
                    return
    raise AssertionError(('no wall near', x, y, c))


