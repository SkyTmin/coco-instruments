# Клетки, на которых стоят (для настенного и нор).
FLOORISH = '.itsgrpkIHANd' + 'Ff8OUVjemqxy0134679'


def paint(m, x0, y0, x1, y1, ch, share=1.0, ok='.'):
    rng = m.rng
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            if 0 <= y < m.h and 0 < x < W - 1 and m.g[y][x] in ok and not m.lock[y][x]:
                if rng.random() < share:
                    m.g[y][x] = ch


def speckle(m, x0, y0, x1, y1, ch, n, ok='.', gap=2):
    """Раскидать `n` клеток `ch` по полу прямоугольника, не ближе `gap`."""
    rng = m.rng
    cells = [(x, y) for y in range(y0, y1 + 1) for x in range(x0, x1 + 1)
             if 0 <= y < m.h and 0 < x < W - 1 and m.g[y][x] in ok and not m.lock[y][x]]
    rng.shuffle(cells)
    placed = []
    for (x, y) in cells:
        if len(placed) >= n:
            break
        if any(abs(x - a) + abs(y - b) < gap for a, b in placed):
            continue
        m.g[y][x] = ch
        placed.append((x, y))
    return placed


def disc(m, cx, cy, r, ch, ok=None):
    """Круг клеток (центр клетки ближе r к точке cx, cy)."""
    out = []
    for y in range(int(cy - r) - 1, int(cy + r) + 2):
        for x in range(int(cx - r) - 1, int(cx + r) + 2):
            if not m.inb(x, y):
                continue
            if math.hypot(x + 0.5 - cx, y + 0.5 - cy) <= r:
                if ok is None or m.g[y][x] in ok:
                    m.g[y][x] = ch
                    out.append((x, y))
    return out


def blob(m, cx, cy, r, ch, ok, rough=0.35):
    """Пятно с неровным краем — только по клеткам из `ok`."""
    ph = [m.rng.random() * 6.283 for _ in range(3)]
    for y in range(int(cy - r * 1.5) - 1, int(cy + r * 1.5) + 2):
        for x in range(int(cx - r * 1.5) - 1, int(cx + r * 1.5) + 2):
            if not m.inb(x, y) or m.g[y][x] not in ok or m.lock[y][x]:
                continue
            dx = x + 0.5 - cx
            dy = y + 0.5 - cy
            a = math.atan2(dy, dx)
            k = r * (1 + rough * (0.6 * math.sin(3 * a + ph[0]) + 0.4 * math.sin(5 * a + ph[1])))
            if dx * dx + dy * dy <= k * k:
                m.g[y][x] = ch


def hole(m, x, y):
    """Нора в стене, откуда лезут: стена, рядом пол любого вида."""
    def ok(x, y):
        return (m.get(x, y) == '#' and not m.lock[y][x] and 0 < x < W - 1 and any(
            m.get(x + dx, y + dy) in FLOORISH for dx, dy in ((0, 1), (1, 0), (-1, 0), (0, -1))))
    if ok(x, y):
        m.put(x, y, 'o')
        return
    for r in range(1, 6):
        for dx, dy in ((-r, 0), (r, 0), (0, -r), (0, r)):
            if ok(x + dx, y + dy):
                print(f'  сдвиг o ({x},{y}) -> ({x+dx},{y+dy})', file=sys.stderr)
                m.put(x + dx, y + dy, 'o')
                return
    print(f'  НЕТ места норе ({x},{y})', file=sys.stderr)


def face(m, x, y, c):
    """Настенное: стена, под ней пол. Мимо — ищем рядом по ряду."""
    for dy in (0, 1, -1, 2, -2):
        for dx in (0, 1, -1, 2, -2, 3, -3):
            xx = x + dx
            yy = y + dy
            # Стена под защитой (`protect`) годится: она останется стеной.
            if m.get(xx, yy) == '#' and m.get(xx, yy + 1) in FLOORISH:
                if dx or dy:
                    print(f'  сдвиг {c} ({x},{y}) -> ({xx},{yy})', file=sys.stderr)
                m.put(xx, yy, c)
                return
    raise SystemExit(f'НЕТ стены для {c} ({x},{y})')


def walls_around(m, x0, y0, x1, y1):
    """Сплошная стена по контуру прямоугольника (и защита от дрожи)."""
    for x in range(x0, x1 + 1):
        m.set(x, y0, '#')
        m.set(x, y1, '#')
    for y in range(y0, y1 + 1):
        m.set(x0, y, '#')
        m.set(x1, y, '#')
    m.protect(x0, y0, x1, y1)


def wall_row(m, x0, x1, y, ch, every=1, phase=0):
    """Настенная отделка по ряду: стена, под которой пол."""
    for x in range(x0, x1 + 1):
        if (x - phase) % every:
            continue
        if m.get(x, y) == '#' and m.get(x, y + 1) in FLOORISH:
            m.g[y][x] = ch


def crown(m, x0, x1, y, ch, every=1, phase=0):
    """Отделка по верхней кромке зала: от клетки (x, y) вверх до стены."""
    for x in range(x0, x1 + 1):
        if (x - phase) % every:
            continue
        yy = y
        while yy > 0 and m.get(x, yy) in FLOORISH:
            yy -= 1
        if m.get(x, yy) == '#' and m.get(x, yy + 1) in FLOORISH:
            m.g[yy][x] = ch


def block(m, x0, y0, x1, y1):
    """Сплошная порода с защитой: отрезать один район от другого."""
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            m.set(x, y, '#')
    m.protect(x0, y0, x1, y1)


