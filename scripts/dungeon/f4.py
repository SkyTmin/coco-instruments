def niche_wall(m, x0, x1, y, kinds='NNH', burrows=()):
    """Ниши на северной стене ряда `y` (под ними пол): кости, гроб, нора."""
    for i, x in enumerate(range(x0, x1 + 1)):
        if m.get(x, y) != '#' or m.get(x, y + 1) not in '.,kgr':
            continue
        if x in burrows:
            m.put(x, y, 'o')
        else:
            m.put(x, y, kinds[i % len(kinds)])


def loculi(m, x0, x1, y0, y1, step=5, depth=2, burrows=()):
    """Галерея с погребальными нишами: по бокам хода x0…x1 через `step`
    рядов вырезаны альковы глубиной `depth`; на северной стене алькова —
    ниша (лицо стены видно только над полом)."""
    for y in range(y0, y1 + 1, step):
        for side in (-1, 1):
            if side < 0:
                ax0, ax1 = x0 - depth, x0 - 1
            else:
                ax0, ax1 = x1 + 1, x1 + depth
            m.rect(ax0, y, ax1, y + 1)
            niche_wall(m, ax0, ax1, y - 1, 'NH' if side < 0 else 'HN',
                       burrows=[ax0] if (y // step) % 3 in burrows else ())


