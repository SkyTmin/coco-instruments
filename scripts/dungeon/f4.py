"""Этаж 4 «Двойная крипта» — карта (кисти brush.py).

Мотив — двойное подземелье: снизу обычный склеп (лифт, галерея ниш, ротонда,
развилка на оссуарий и зал стражи, зал прощаний), а за узким порогом —
второй, настоящий зал: колоннада со статуями и в её конце, за воротами,
огромный зал с каменным идолом на троне.

Районы (снизу вверх, как в `f4.ts`):
  f4crypt — «Крипта», вход с лифтом;
  f4sanct — «Святилище», колоннада, арена идола, печать и лестница.

Свои буквы (легенда — `AreaSpec.legend` в `src/lib/dungeon-floors/f4.ts`):
  q саркофаг   i свечи   U урна (бьётся)   O колонна   Z груда черепов
  A стойка лат  F жаровня  W открытый гроб  k кости на полу  g надгробная плита
  r дорожка     x трещины в полу
  N ниша с костями (стена)   H ниша с гробом (стена)   w барельеф (стена)
  Q мёртвая статуя на постаменте   J постамент живого стража
  j постамент стража идола (арена)   I трон идола   h помост   p плита света
  z скрижаль заповедей

Запуск: python3 scripts/dungeon/f4.py  (--show — напечатать карты)
"""
import os
