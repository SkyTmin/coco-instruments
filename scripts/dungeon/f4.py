# Крипта (f4crypt): 136 рядов, ряд 0 стыкуется со святилищем (x 30…33).
# ---------------------------------------------------------------------------

def crypt():
    m = Map(136, seed=404, cave=",")
    H = m.h

    # Порог наверх: узкий ход к святилищу.
    m.rect(30, 0, 33, 17)
    # Два алькова со свечами по сторонам порога — лампы на их северной стене.
    m.rect(28, 8, 29, 9)
    m.rect(34, 8, 35, 9)
    m.put(28, 7, 'L')
    m.put(35, 7, 'L')
    m.put(28, 9, 'i')
    m.put(35, 9, 'i')

    # Зал прощаний: ряды саркофагов вдоль дорожки, свечи, засада посередине.
    # Телефон видит ~10 клеток в ширину: главное стоит в пяти от дорожки.
    m.rect(12, 18, 51, 36)
    for y in range(18, 37):
        for x in (31, 32):
            m.put(x, y, 'r')
    for x in (26, 36, 18, 44):
        for y in (21, 26, 31):
            m.put(x, y, 'q')
            m.put(x + 1, y, 'e')
    for x, y in ((29, 21), (34, 21), (29, 31), (34, 31), (14, 20), (49, 20), (14, 34), (49, 34)):
        m.put(x, y, 'i')
    m.put(29, 27, 'a')
    for x, y in ((24, 35), (39, 35), (12, 27), (51, 27), (28, 19), (35, 19)):
        m.put(x, y, 'U')
    for x, y in ((23, 24), (40, 29), (22, 29), (41, 24)):
        m.put(x, y, 'g')
    niche_wall(m, 12, 29, 17, 'NNHN', burrows=(15, 24))
    niche_wall(m, 34, 51, 17, 'NHNN', burrows=(39, 48))
    m.put(29, 17, 'L')
    m.put(34, 17, 'L')

    # Оссуарий (запад): два зала костей, в верхнем — логово некроманта.
    # O2 — верхний: алтарь из черепов, свечи, спящая стая.
    m.rect(6, 42, 22, 56)
    m.rect(14, 37, 16, 41)              # выход в зал прощаний
    for x, y in ((9, 45), (19, 45), (9, 53), (19, 53)):
        m.put(x, y, 'Z')
    m.put(14, 49, 'q')
    m.put(13, 47, 'i')
    m.put(16, 47, 'i')
    for x, y in ((8, 50), (11, 55), (20, 50), (17, 43), (12, 43)):
        m.put(x, y, 'k')
    m.put(14, 52, 'R')
    niche_wall(m, 6, 22, 41, 'NNNH', burrows=(8, 20))
    # O1 — нижний, большой: колонны из черепов.
    m.rect(5, 60, 18, 77)
    m.rect(8, 56, 10, 60)               # ход O1 → O2
    for x in (7, 11, 15):
        for y in (64, 70):
            m.put(x, y, 'Z')
    for x, y in ((6, 62), (17, 66), (9, 74), (13, 61), (6, 71), (16, 75), (12, 67)):
        m.put(x, y, 'k')
    m.put(11, 73, 'R')
    niche_wall(m, 5, 18, 59, 'NHN', burrows=(6, 17))
    m.put(12, 59, 'L') if m.get(12, 59) in 'NH' else None
    # Ход из ротонды на запад, в O1.
    m.rect(13, 78, 18, 83)
    m.rect(13, 81, 22, 83)

    # Короткий путь: из часовни лифта вдоль западной стены к решётке O2.
    m.rect(1, 124, 19, 126)
    m.rect(1, 48, 2, 126)
    m.rect(1, 48, 4, 50)
    m.put(5, 49, 'D')                   # открывается изнутри оссуария (с востока)
    m.put(1, 90, 'u')
    m.put(1, 110, 'u')
    # Тайник в стене короткого пути.
    m.rect(4, 96, 6, 98)
    m.put(3, 97, '%')
    m.put(5, 97, '$')
    m.put(2, 70, 'i')

    # Зал стражи (восток): колонны и стойки лат вдоль дорожки, стража.
    m.rect(40, 56, 58, 74)
    for y in range(56, 75):
        m.put(49, y, 'r')
    for x in (46, 52):
        for y in (59, 64, 69):
            m.put(x, y, 'O')
    for x in (44, 54):
        for y in (61, 66, 71):
            m.put(x, y, 'A')
    m.put(51, 66, 'R')
    m.put(42, 58, 'U')
    m.put(56, 72, 'U')
    niche_wall(m, 40, 58, 55, 'NHN', burrows=(42, 56))
    m.put(45, 55, 'L')
    m.put(53, 55, 'L')
    # Коридор стражи: узкий и ломаный, латника в нём не обойти.
    m.rect(54, 40, 56, 55)
    m.rect(42, 38, 56, 40)
    m.rect(42, 37, 44, 38)
    m.wall_obj(48, 37, 'L')
    m.put(50, 39, 'U')
    # Ход из ротонды на восток; на север — в зал стражи, дальше — штольня.
    m.rect(41, 81, 52, 83)
    m.rect(48, 75, 50, 83)
    m.rect(53, 77, 61, 87)
    m.wall_obj(57, 76, 'M')
    m.put(54, 86, 'C')
    m.put(60, 78, 'B')
    m.put(55, 79, 'C')
    m.put(59, 85, 'k')

    # Ротонда: развилка, в середине большой саркофаг и четыре колонны.
    m.ell(31.5, 84.5, 10, 7, c='.', natural=False, rough=0.08)
    m.put(31, 84, 'q')
    m.put(32, 84, 'e')
    for x, y in ((26, 81), (37, 81), (26, 88), (37, 88)):
        m.put(x, y, 'O')
    for x, y in ((29, 80), (34, 80), (29, 89), (34, 89)):
        m.put(x, y, 'i')
    m.put(31, 86, 'g')
    m.put(24, 84, 'k')
    m.put(39, 85, 'k')
    m.wall_obj(31, 76, 'L')

    # Галерея ниш: от часовни лифта на север к ротонде.
    m.rect(29, 91, 34, 115)
    loculi(m, 29, 34, 94, 112, step=5, depth=2, burrows=(0,))
    m.put(31, 102, 'g')
    m.put(32, 108, 'g')
    m.put(30, 97, 'k')
    # Западный склеп: саркофаги, тайник за треснувшей стеной.
    m.rect(14, 100, 23, 108)
    m.rect(24, 103, 28, 105)
    for x, y in ((16, 102), (20, 102), (16, 106), (20, 106)):
        m.put(x, y, 'q')
        m.put(x + 1, y, 'e')
    m.put(18, 104, 'i')
    m.put(15, 108, 'U')
    m.put(22, 100, 'U')
    niche_wall(m, 14, 23, 99, 'HNNH')
    m.rect(10, 102, 12, 104)
    m.put(13, 103, '%')
    m.put(11, 103, '$')
    # Восточный склеп: открытые гробы и спящие кости.
    m.rect(40, 96, 49, 104)
    m.rect(35, 99, 39, 101)
    m.put(42, 97, 'W')
    m.put(47, 97, 'W')
    m.put(42, 103, 'W')
    m.put(47, 103, 'W')
    m.put(45, 100, 'R')
    m.put(44, 98, 'k')
    m.put(48, 101, 'k')
    niche_wall(m, 40, 49, 95, 'NNHN', burrows=(44,))

    # Часовня лифта.
    m.rect(20, 116, 43, 134)
    m.floor(31, 128, 'E')
    for x, y in ((28, 117), (35, 117), (21, 133), (42, 133), (27, 125), (36, 125)):
        m.put(x, y, 'i')
    for x, y in ((27, 133), (36, 133), (22, 124)):
        m.put(x, y, 'U')
    m.put(38, 121, 'q')
    m.put(39, 121, 'e')
    m.put(24, 121, 'q')
    m.put(25, 121, 'e')
    for y in range(116, 125):
        for x in (31, 32):
            m.put(x, y, 'r')
    niche_wall(m, 20, 28, 115, 'NHN')
    niche_wall(m, 35, 43, 115, 'NHN')
    m.put(24, 115, 'L')
    m.put(39, 115, 'L')
    m.put(27, 115, 'b')
    return check(m, 'f4crypt')


# ---------------------------------------------------------------------------
# Святилище (f4sanct): 118 рядов, ряд 117 стыкуется с криптой (x 30…33).
# ---------------------------------------------------------------------------

ARENA_X0, ARENA_X1 = 23, 39      # зал идола: 17 клеток, середина — 31,5
ARENA_Y0, ARENA_Y1 = 5, 56


def sanct():
    m = Map(118, seed=4404, cave=',')
    H = m.h

    # Порог снизу: узкий ход из крипты.
    m.rect(30, 101, 33, H - 1)
    m.rect(28, 108, 29, 109)
    m.rect(34, 108, 35, 109)
    m.put(28, 107, 'L')
    m.put(35, 107, 'L')
    m.put(28, 109, 'i')
    m.put(35, 109, 'i')

    # Колоннада — «второй зал»: огромный. Вдоль дорожки — неф из колонн и
    # статуй в четырёх клетках от середины (их видно с дорожки), дальше —
    # боковые нефы со статуями у стен. Часть статуй — живые стражи (J).
    m.rect(4, 58, 58, 100)
    for y in range(58, 101):
        for x in (30, 31, 32):
            m.put(x, y, 'r')
    live = {(27, 74), (35, 82), (27, 90), (35, 66), (5, 76), (57, 88)}
    for i, y in enumerate(range(62, 99, 4)):
        for x in (27, 35):
            if i % 2 == 0:
                m.put(x, y, 'O')
            else:
                m.put(x, y, 'J' if (x, y) in live else 'Q')
    for x in (14, 48):
        for y in range(64, 99, 8):
            m.put(x, y, 'O')
    for x in (5, 57):
        for y in range(64, 99, 6):
            m.put(x, y, 'J' if (x, y) in live else 'Q')
    for x, y in ((10, 60), (52, 60), (10, 98), (52, 98), (26, 59), (36, 59), (21, 80), (41, 80)):
        m.put(x, y, 'F')
    for x, y in ((18, 70), (45, 66), (20, 90), (44, 95), (24, 78), (38, 83), (9, 84), (54, 79)):
        m.put(x, y, 'x')
    for x, y in ((12, 66), (51, 92), (17, 96), (46, 62), (23, 69), (39, 93)):
        m.put(x, y, 'k')
    m.put(19, 84, 'R')
    m.put(44, 72, 'R')
    m.put(20, 64, 'U')
    m.put(43, 97, 'U')
    niche_wall(m, 4, 58, 57, 'wwNw', burrows=(12, 20, 43, 51))
    m.put(28, 60, 'T')

    # Колоннада → лифт (юго-восток) и шахта (юго-запад).
    m.rect(46, 102, 58, 112)
    m.rect(50, 101, 53, 101)
    m.floor(52, 108, 'E')
    niche_wall(m, 46, 58, 101, 'N')
    m.put(47, 101, 'b') if m.get(47, 101) in 'N#' else None
    m.put(55, 101, 'L') if m.get(55, 101) in 'N#' else None
    m.put(47, 111, 'i')
    m.put(57, 111, 'i')
    m.rect(4, 102, 16, 110)
    m.rect(8, 101, 10, 101)
    m.put(12, 101, 'M')
    m.put(5, 101, 'L') if m.get(5, 101) == '#' else None
    m.put(15, 109, 'B')
    m.put(5, 106, 'C')
    m.put(14, 104, 'x')

    # Арена: зал идола. Выход — только ворота снизу. Ширина — чтобы стражей
    # у дорожки было видно с неё (телефон показывает ~10 клеток).
    m.rect(ARENA_X0, ARENA_Y0, ARENA_X1, ARENA_Y1)
    for x in range(30, 33):
        m.put(x, ARENA_Y1 + 1, 'G')
    for y in range(ARENA_Y0 + 6, ARENA_Y1 + 1):
        for x in (30, 31, 32):
            m.put(x, y, 'r')
    m.put(26, 53, 'K')
    # Помост и трон.
    for y in range(ARENA_Y0, ARENA_Y0 + 6):
        for x in range(27, 36):
            m.put(x, y, 'h')
    m.put(31, ARENA_Y0 + 2, 'I')
    m.put(25, ARENA_Y0 + 3, 'z')
    for x, y in ((24, 6), (38, 6), (23, 17), (39, 17), (23, 33), (39, 33), (23, 49), (39, 49)):
        m.put(x, y, 'F')
    # Постаменты стражей вдоль дорожки: пять пар, в четырёх клетках от оси.
    for y in (16, 24, 32, 40, 48):
        m.put(27, y, 'j')
        m.put(35, y, 'j')
    # Плиты света 2×2 (левый верхний угол). Пары симметричны оси зала
    # (31,5): левая (a, a+1), правая (61-a, 62-a). Внутренние — у дорожки,
    # наружные — у стен, через ряд.
    plates = []
    for a, y in ((28, 12), (24, 20), (28, 28), (24, 36), (28, 44), (24, 52)):
        plates += [(a, y), (61 - a, y)]
    for (px, py) in plates:
        for dy in (0, 1):
            for dx in (0, 1):
                m.put(px + dx, py + dy, 'p')
    for x, y in ((25, 47), (37, 25), (26, 38), (36, 55)):
        m.put(x, y, 'x')
    niche_wall(m, ARENA_X0, ARENA_X1, ARENA_Y0 - 1, 'w')

    # Печать и ход к лестнице: вдоль запада, в обход арены.
    m.rect(6, 6, 8, 57)
    for x in (6, 7, 8):
        m.put(x, 55, 'S')
    m.rect(6, 2, 18, 7)
    m.put(15, 4, '>')
    m.put(7, 30, 'i')
    niche_wall(m, 6, 18, 1, 'w')
    return check(m, 'f4sanct')


if __name__ == '__main__':
    c = crypt()
    s = sanct()
    if '--show' in sys.argv:
        show(s, 'S')
        show(c, 'C')
    write_floor(4, {'MAP_F4_SANCT': s, 'MAP_F4_CRYPT': c},
                note='Святилище сверху (глубже), крипта снизу — как в мире.')
