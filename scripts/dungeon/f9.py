def paint(m, x0, y0, x1, y1, ch, share=1.0, ok='.,'):
    for (x, y) in cells(m, x0, y0, x1, y1, ok):
        if m.rng.random() < share:
            m.g[y][x] = ch


def blob(m, cx, cy, rx, ry, ch, ok='.,', rough=0.25):
    """Неровное пятно буквы `ch` поверх пола (лужа, трясина, мох)."""
    import math
    ph = [m.rng.random() * 6.283 for _ in range(3)]
    for y in range(int(cy - ry * 1.5) - 1, int(cy + ry * 1.5) + 2):
        for x in range(int(cx - rx * 1.5) - 1, int(cx + rx * 1.5) + 2):
            if not m.inb(x, y) or m.g[y][x] not in ok or m.lock[y][x]:
                continue
            dx = (x + 0.5 - cx) / rx
            dy = (y + 0.5 - cy) / ry
            a = math.atan2(dy, dx)
            k = 1 + rough * (0.6 * math.sin(3 * a + ph[0]) + 0.3 * math.sin(5 * a + ph[1])
                             + 0.2 * math.sin(7 * a + ph[2]))
            if dx * dx + dy * dy <= k * k:
                m.g[y][x] = ch


def faces(m, x0, y0, x1, y1):
    """Стены, под которыми пол: их лицо видно."""
    out = []
    for y in range(max(0, y0), min(m.h - 1, y1 + 1)):
        for x in range(max(1, x0), min(W - 1, x1 + 1)):
            if m.g[y][x] == '#' and m.g[y + 1][x] in '.,mqrsJN' and not m.lock[y][x]:
                out.append((x, y))
    return out


def sprinkle(m, pts, ch, share, gap=0):
    placed = []
    for (x, y) in pts:
        if m.rng.random() >= share:
            continue
        if any(abs(x - px) + abs(y - py) < gap for px, py in placed):
            continue
        m.put(x, y, ch)
        placed.append((x, y))
    return placed


def scatter(m, x0, y0, x1, y1, ch, n, ok='.,mq', gap=2, wall_gap=1):
    """Раскидать `n` предметов по полу, не вплотную к стене и друг к другу."""
    pts = cells(m, x0, y0, x1, y1, ok)
    m.rng.shuffle(pts)
    placed = []
    for (x, y) in pts:
        if len(placed) >= n:
            break
        if wall_gap and any(m.get(x + dx, y + dy) == '#'
                            for dx in range(-wall_gap, wall_gap + 1)
                            for dy in range(-wall_gap, wall_gap + 1)):
            continue
        if any(abs(x - px) + abs(y - py) < gap for px, py in placed):
            continue
        m.put(x, y, ch)
        placed.append((x, y))
    return placed


def ring(m, x, y, ch):
    """Круг-телепорт: клетка пола, вокруг — пол (на круг встают)."""
    for dy in (-1, 0, 1):
        for dx in (-1, 0, 1):
            if m.g[y + dy][x + dx] == '#':
                m.g[y + dy][x + dx] = '.'
    m.put(x, y, ch)


def dress_walls(m, x0, y0, x1, y1, vine=0.06, glow=0.05, lamp=0.03, hang=0.035, gap=2):
    """Лица стен: лианы по кладке, светящийся мох, грибы-лампы, свисающие
    лианы. Украшенные лица не липнут друг к другу — иначе стена пестрит."""
    f = faces(m, x0, y0, x1, y1)
    m.rng.shuffle(f)
    done = []
    for (x, y) in f:
        r = m.rng.random()
        if r < lamp:
            ch, g = 'H', 6
        elif r < lamp + hang:
            ch, g = 'V', gap + 1
        elif r < lamp + hang + glow:
            ch, g = 'g', gap + 1
        elif r < lamp + hang + glow + vine:
            ch, g = 'h', 0
        else:
            continue
        if g and any(abs(x - px) + abs(y - py) <= g and pc != 'h' for px, py, pc in done):
            continue
        m.put(x, y, ch)
        done.append((x, y, ch))


