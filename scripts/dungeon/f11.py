def reach(rows, sx, sy, passable=PASS):
    h = len(rows)
    seen = [[False] * W for _ in range(h)]
    q = deque([(sx, sy)])
    seen[sy][sx] = True
    while q:
        x, y = q.popleft()
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            nx, ny = x + dx, y + dy
            if 0 <= nx < W and 0 <= ny < h and not seen[ny][nx] and rows[ny][nx] in passable:
                seen[ny][nx] = True
                q.append((nx, ny))
    return seen


