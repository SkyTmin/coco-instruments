def preview(areas, path, k=6):
    """Смотр карты: цвет клетки, вещи — точкой, ветер — чёрточкой."""
    from PIL import Image, ImageDraw
    rows = [r for _, rs, _ in areas for r in rs]
    wind = [r for _, _, ws in areas for r in ws]
    h = len(rows)
    im = Image.new('RGB', (W * k, h * k))
    d = ImageDraw.Draw(im)
    dirs = {'8': (0, -1), '6': (1, 0), '2': (0, 1), '4': (-1, 0), '9': (1, -1), '3': (1, 1),
            '1': (-1, 1), '7': (-1, -1), 'N': (0, -1), 'E': (1, 0), 'S': (0, 1), 'W': (-1, 0)}
    for y in range(h):
        for x in range(W):
            c = rows[y][x]
            col = PREVIEW.get(c)
            if col is None:
                col = (200, 200, 200) if c in FLOOR else (255, 0, 0)
                d.rectangle([x * k, y * k, x * k + k - 1, y * k + k - 1], fill=(104, 164, 72))
                d.ellipse([x * k + 1, y * k + 1, x * k + k - 2, y * k + k - 2], fill=col)
            else:
                d.rectangle([x * k, y * k, x * k + k - 1, y * k + k - 1], fill=col)
            wc = wind[y][x]
            if wc != '.':
                cx, cy = x * k + k / 2, y * k + k / 2
                if wc in dirs:
                    ux, uy = dirs[wc]
                    col = (255, 255, 255) if wc.isdigit() else (255, 40, 40)
                    d.line([cx - ux * k * 0.4, cy - uy * k * 0.4, cx + ux * k * 0.4, cy + uy * k * 0.4],
                           fill=col)
                    d.point([cx + ux * k * 0.4, cy + uy * k * 0.4], fill=(0, 0, 0))
                else:
                    d.rectangle([cx - 1, cy - 1, cx + 1, cy + 1], fill=(255, 0, 255))
    y0 = 0
    for name, rs, _ in areas:
        d.text((4, y0 * k + 2), name, fill=(0, 0, 0))
        y0 += len(rs)
    im.save(path)
    print('смотр', path, im.size, file=sys.stderr)


def main():
    g_rows, g_wind = check_rows(area_garden(), 'f11')
    a_rows, a_wind = check_rows(area_aqua(), 'f11aqua')
    c_rows, c_wind = check_rows(area_castle(), 'f11castle')
    # Стыки районов: низ верхнего и верх нижнего открыты в одних столбцах.
    for top, bottom, name in ((a_rows, g_rows, 'акведук/сады'), (c_rows, a_rows, 'замок/акведук')):
        lo = [x for x in range(W) if top[-1][x] in PASS]
        hi = [x for x in range(W) if bottom[0][x] in PASS]
        assert lo == hi, (name, lo, hi)
    world = c_rows + a_rows + g_rows
    wind = c_wind + a_wind + g_wind
    # Обход от лифта входа: босс, шахты, печать — лестница.
    ly = next(y for y in range(len(world)) if 'E' in world[y] and y >= len(c_rows) + len(a_rows))
    lx = world[ly].index('E')
    seen = reach(world, lx, ly)
    ky = next(y for y in range(len(world)) if 'K' in world[y])
    kx = world[ky].index('K')
    assert seen[ky][kx], 'босс недостижим'
    for y, r in enumerate(world):
        for x, c in enumerate(r):
            if c == 'M':
                assert seen[y + 1][x], ('шахта', x, y)
            if c == '$':
                assert seen[y][x], ('тайник', x, y)
            if c == 'E':
                assert seen[y][x], ('лифт', x, y)
    sealed = reach(world, lx, ly, PASS - set('S'))
    for y, r in enumerate(world):
        for x, c in enumerate(r):
            if c == '>':
                assert not sealed[y][x] and seen[y][x], 'лестница за печатью'
    # Арена: заливка от K по полу (без ворот) не выходит к лифту и лестнице.
    arena = reach(world, kx, ky, FLOOR - set('M'))
    n = sum(sum(1 for v in row if v) for row in arena)
    assert 40 < n < 1500, ('арена', n)
    assert not arena[ly][lx], 'лифт в арене'
    print('арена', n, 'клеток', file=sys.stderr)
    areas = [('f11castle', c_rows, c_wind), ('f11aqua', a_rows, a_wind), ('f11', g_rows, g_wind)]
    if '--show' in sys.argv:
        show(world)
    if '--png' in sys.argv:
        preview(areas, sys.argv[sys.argv.index('--png') + 1])
    if '--write' in sys.argv or '--png' not in sys.argv:
        write_floor(11, {
            'MAP_F11_GARDEN': g_rows,
            'MAP_F11_AQUA': a_rows,
            'MAP_F11_CASTLE': c_rows,
            'WIND_F11_GARDEN': g_wind,
            'WIND_F11_AQUA': a_wind,
            'WIND_F11_CASTLE': c_wind,
        }, note='Слои ветра WIND_* — по символу на клетку (см. шапку f11.py).')


if __name__ == '__main__':
    main()
