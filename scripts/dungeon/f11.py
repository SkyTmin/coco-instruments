SKY = '_'
EDGE = '|'
# Пол (всё, по чему ходят; вещи — на полу).
FLOOR = set('gpmfskqrjzdexhw13579') | set('OVti&*+:;[]?^(){}<0468') | set('ETK$M>')
WALLS = set('HAUNWQ|IFJZL')
DEEP = set('_y/2')
# Для обхода: проходимое движком (ворота, решётки, трещины и печати — тоже).
PASS = (FLOOR - set('M')) | set('GD%S')
# Земля, на которую можно ставить вещи.
GROUND = set('gpmfskqrjzdhx')
WIND_OK = set('.86249317NESWabcdefghij')


class Isle(Map):
    """Карта района: небо со стенкой края, острова, мосты и слой ветра."""

    def __init__(self, h, seed):
        super().__init__(h, seed, cave='g')
        self.wind = [['.'] * W for _ in range(h)]
        for y in range(h):
            for x in range(W):
                self.g[y][x] = EDGE if x in (0, W - 1) else SKY

    # --- Формы -------------------------------------------------------------

    def isle(self, cx, cy, rx, ry, c='g', p=2.6, rough=0.1, over=SKY):
        """Остров: суперэллипс (p=2 — овал, 4 — почти прямоугольник) с
        неровным краем. Кладёт `c` только поверх `over` (по умолчанию — неба)."""
        ph = [self.rng.random() * 6.283 for _ in range(3)]
        for y in range(int(cy - ry) - 2, int(cy + ry) + 3):
            for x in range(int(cx - rx) - 2, int(cx + rx) + 3):
                if not self.inb(x, y):
                    continue
                dx = abs(x + 0.5 - cx) / rx
                dy = abs(y + 0.5 - cy) / ry
                a = math.atan2(dy, dx)
                k = 1 + rough * (0.6 * math.sin(3 * a + ph[0]) + 0.4 * math.sin(7 * a + ph[1])
                                 + 0.25 * math.sin(11 * a + ph[2]))
                if dx ** p + dy ** p <= k ** p and (over is None or self.g[y][x] in over):
                    self.g[y][x] = c

    def box(self, x0, y0, x1, y1, c, over=None):
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1):
                if self.inb(x, y) and (over is None or self.g[y][x] in over):
                    self.g[y][x] = c

    def fill(self, x0, y0, x1, y1, c, share=1.0, ok='g'):
        """Перекрасить пол вида `ok` в `c` с долей `share`."""
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1):
                if self.inb(x, y) and self.g[y][x] in ok and not self.lock[y][x]:
                    if share >= 1 or self.rng.random() < share:
                        self.g[y][x] = c

    def blob(self, cx, cy, rx, ry, c, ok='g'):
        """Пятно пола (мох, земля) с мягким краем по шуму."""
        for y in range(int(cy - ry) - 1, int(cy + ry) + 2):
            for x in range(int(cx - rx) - 1, int(cx + rx) + 2):
                if not self.inb(x, y) or self.g[y][x] not in ok or self.lock[y][x]:
                    continue
                d = ((x + 0.5 - cx) / rx) ** 2 + ((y + 0.5 - cy) / ry) ** 2
                if d + (noise(x, y, 2.3, 11) - 0.5) * 0.7 <= 1:
                    self.g[y][x] = c

    def vbridge(self, x0, x1, y0, y1, c='j'):
        self.box(x0, min(y0, y1), x1, max(y0, y1), c, over=SKY + 'y/')

    def hbridge(self, x0, x1, y0, y1, c='j'):
        self.box(min(x0, x1), y0, max(x0, x1), y1, c, over=SKY + 'y/')

    def edge(self, x, y):
        """Клетка пола у края (рядом небо)."""
        return any(self.get(x + dx, y + dy) in DEEP
                   for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)))

    # --- Вещи --------------------------------------------------------------

    def obj(self, x, y, c, ok=GROUND):
        """Вещь на полу; мимо — ближайшая свободная клетка рядом."""
        if self.g[y][x] in ok and not self.lock[y][x]:
            self.put(x, y, c)
            return (x, y)
        for r in (1, 2):
            for dy in range(-r, r + 1):
                for dx in range(-r, r + 1):
                    if self.inb(x + dx, y + dy) and self.g[y + dy][x + dx] in ok \
                            and not self.lock[y + dy][x + dx]:
                        print(f'  сдвиг {c} ({x},{y}) -> ({x+dx},{y+dy})', file=sys.stderr)
                        self.put(x + dx, y + dy, c)
                        return (x + dx, y + dy)
        raise AssertionError(('no floor near', x, y, c))

    def sky_obj(self, x, y, c):
        """Вещь в небе (облако, летучий камень): только на чистом небе."""
        assert self.g[y][x] == SKY, ('not sky', x, y, c, self.g[y][x])
        self.put(x, y, c)

    def face(self, x, y, c):
        """Настенное: стена, под ней пол."""
        assert self.g[y][x] in WALLS, ('not wall', x, y, c, self.g[y][x])
        assert self.g[y + 1][x] in FLOOR, ('no floor below', x, y, c, self.g[y + 1][x])
        self.put(x, y, c)

    def hole(self, x, y):
        """Нора в скале или кладке: стена, рядом пол."""
        def ok(x, y):
            return (self.get(x, y) in 'AUWQH' and not self.lock[y][x] and 0 < x < W - 1
                    and any(self.get(x + dx, y + dy) in GROUND
                            for dx, dy in ((0, 1), (1, 0), (-1, 0), (0, -1))))
        for r in range(0, 5):
            for dx, dy in ((0, 0), (-r, 0), (r, 0), (0, -r), (0, r)):
                if ok(x + dx, y + dy):
                    if r:
                        print(f'  сдвиг o ({x},{y}) -> ({x+dx},{y+dy})', file=sys.stderr)
                    self.put(x + dx, y + dy, 'o')
                    return
        raise AssertionError(('no burrow spot', x, y))

    def scatter(self, x0, y0, x1, y1, c, n, ok='g', gap=2, edge=None):
        """`n` вещей `c` по полу прямоугольника, не ближе `gap` друг к другу.
        `edge`=True — только у края, False — только не у края."""
        cells = [(x, y) for y in range(y0, y1 + 1) for x in range(x0, x1 + 1)
                 if self.inb(x, y) and self.g[y][x] in ok and not self.lock[y][x]
                 and (edge is None or self.edge(x, y) == edge)]
        self.rng.shuffle(cells)
        placed = []
        for (x, y) in cells:
            if len(placed) >= n:
                break
            if any(abs(x - a) + abs(y - b) < gap for a, b in placed):
                continue
            self.put(x, y, c)
            placed.append((x, y))
        return placed

    # --- Ветер -------------------------------------------------------------

    def gust(self, x0, y0, x1, y1, ch, only=None):
        """Поток на прямоугольнике: только на полу (или на `only`)."""
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1):
                if not self.inb(x, y):
                    continue
                if only is not None and self.g[y][x] not in only:
                    continue
                self.wind[y][x] = ch

    def wind_rows(self):
        return [''.join(r) for r in self.wind]


def check_rows(m, name):
    rows = m.rows()
    for i, r in enumerate(rows):
        assert len(r) == W, (name, i, len(r))
        assert r[0] == EDGE and r[-1] == EDGE, (name, i, r)
    wr = m.wind_rows()
    for i, r in enumerate(wr):
        assert len(r) == W and all(c in WIND_OK for c in r), (name, i, r)
    return rows, wr


