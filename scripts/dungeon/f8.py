class F8(Map):
    """Карта с помощниками замка: комнаты, энгава, двери, перегородки."""

    def room(self, x0, y0, x1, y1, c=':'):
        self.rect(x0, y0, x1, y1, c)

    def fill_if(self, x0, y0, x1, y1, c, only):
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1):
                if self.inb(x, y) and self.g[y][x] in only:
                    self.g[y][x] = c

    def put(self, x, y, c):
        assert self.inb(x, y), (x, y, c)
        self.g[y][x] = c
        self.lock[y][x] = True

    def on_face(self, x, y, c, must=False):
        """Настенное (лампа, окно, дверь, шахта): стена, под ней пол. Нет
        такой стены рядом — пропустить с предупреждением (`must` — упасть)."""
        def ok(x, y):
            return (self.get(x, y) in '#Wsf' and self.get(x, y + 1) in FLOORS
                    and not self.lock[y][x])
        if ok(x, y):
            self.put(x, y, c)
            return (x, y)
        for r in (1, 2, 3):
            for dy in (0, -1, 1):
                for dx in range(-r, r + 1):
                    if ok(x + dx, y + dy):
                        print(f'  сдвиг {c} ({x},{y}) -> ({x+dx},{y+dy})', file=sys.stderr)
                        self.put(x + dx, y + dy, c)
                        return (x + dx, y + dy)
        if must:
            raise AssertionError(('нет стены с полом под ней', x, y, c))
        print(f'  ПРОПУСК {c} ({x},{y}): нет стены с полом под ней', file=sys.stderr)
        return None

    def on_floor(self, x, y, c, ok=FLOORS - set('ETKR$a')):
        if self.get(x, y) in ok and not self.lock[y][x]:
            self.put(x, y, c)
            return
        for r in (1, 2):
            for dy in range(-r, r + 1):
                for dx in range(-r, r + 1):
                    if self.get(x + dx, y + dy) in ok and not self.lock[y + dy][x + dx]:
                        print(f'  сдвиг {c} ({x},{y}) -> ({x+dx},{y+dy})', file=sys.stderr)
                        self.put(x + dx, y + dy, c)
                        return
        raise AssertionError(('нет пола рядом', x, y, c))

    def faces(self, x0, y0, x1, y1):
        out = []
        for y in range(max(0, y0), min(self.h - 1, y1 + 1)):
            for x in range(max(1, x0), min(W - 1, x1 + 1)):
                if self.g[y][x] in '#W' and self.g[y + 1][x] in FLOORS and not self.lock[y][x]:
                    out.append((x, y))
        return out


def castle_walls(m):
    """Вся порода внутри карты — стены замка; края карты остаются `#`."""
    for y in range(m.h):
        for x in range(1, W - 1):
            if m.g[y][x] == '#':
                m.g[y][x] = 'W'


def reach(rows, start, passable=PASS):
    """Обход в ширину по клеткам, проходимым для `passable`."""
    H = len(rows)
    seen = set([start])
    q = [start]
    while q:
        x, y = q.pop()
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            nx, ny = x + dx, y + dy
            if 0 <= nx < W and 0 <= ny < H and (nx, ny) not in seen and rows[ny][nx] in passable:
                seen.add((nx, ny))
                q.append((nx, ny))
    return seen


def find(rows, ch):
    return [(x, y) for y, r in enumerate(rows) for x, c in enumerate(r) if c == ch]


