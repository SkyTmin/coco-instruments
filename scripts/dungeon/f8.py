FLOORS = set('.:;*x-|+}^mnuwrAzq]Fj' + 'tgiypHVUI876543&/()' + 'ETKR$a,>')
PASS = FLOORS | set('GDS%')  # проходимо для обхода (решётки, ворота, печати, трещины)
