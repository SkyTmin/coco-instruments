def junction_h(m, x, y, closed, outer=False):
    """Перегородка поперёк горизонтального хода (3 клетки высотой)."""
    m.rect(x, y - 1, x, y + 1, shift_ch(closed, outer))


def junction_v(m, x, y, closed, outer=False):
    """Перегородка поперёк вертикального хода (3 клетки шириной)."""
    m.rect(x - 1, y, x + 1, y, shift_ch(closed, outer))


def shift_ch(closed, outer):
    """Буква перегородки: ядро (бива Зала струны) — Z/z, окраина (бива
    Галереи доспехов) — [/]. Заглавная/открывающая — стена сейчас."""
    if outer:
        return '[' if closed else ']'
    return 'Z' if closed else 'z'


