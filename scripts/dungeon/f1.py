def scratch(m, x, y):
    """Зарубки на стене — только на лице (под ней пол)."""
    if m.get(x, y) == '#' and m.get(x, y + 1) in '.,~!' and not m.lock[y][x]:
        m.put(x, y, 'Z')


def hole(m, x, y):
    """Нора у точки: ближайшая стена с полом рядом (кисть ищет только по осям)."""
    def ok(x, y):
        return (m.get(x, y) == '#' and not m.lock[y][x] and 0 < x < W - 1 and any(
            m.get(x + dx, y + dy) in '.,~!' for dx, dy in ((0, 1), (1, 0), (-1, 0), (0, -1))))
    best = None
    for dy in range(-7, 8):
        for dx in range(-7, 8):
            if ok(x + dx, y + dy):
                d = dx * dx + dy * dy
                if best is None or d < best[0]:
                    best = (d, x + dx, y + dy)
    assert best, ('no burrow spot', x, y)
    m.put(best[1], best[2], 'o')


def litter(m, x0, y0, x1, y1, seed, dens=0.08, c='k', on='.,'):
    """Россыпь (кости, подстилка) по полу пятнами, а не решетом."""
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            if m.get(x, y) in on and not m.lock[y][x] and noise(x, y, 3.0, seed) > 1 - dens * 4:
                if noise(x * 7, y * 5, 1.0, seed + 1) < 0.5:
                    m.g[y][x] = c


