"""Этаж 2 — «Грибной грот» (v2.81). Карта двух районов на кистях brush.py.

    python3 scripts/dungeon/f2.py            # записать src/lib/dungeon-floors/f2-map.ts
    python3 scripts/dungeon/f2.py --show     # напечатать карты с номерами рядов

Мотив — живая экосистема подземелья: грот, где всё растёт, ползёт и ест
друг друга, а выше — руины крепости, которые грибница уже доедает. Районы
снизу вверх:

  f2grot «Грибной грот» (вход, лифт)  — дикая пещера: грибная роща и
      споровые топи расходятся от лифта развилкой и сходятся у ручья; за
      ручьём — сад мандрагор (зал-ловушка) и корневой ход наверх. Короткий
      путь — ходок от шахты у лифта прямо к саду, за решёткой (открывается
      из сада). Тупик с сундуками: настоящий один, два — мимики.
  f2ruin «Заросшие руины» — плиты и кирпич старой крепости, по которым
      ползёт грибница: сторожка, галерея пустых доспехов на стойках,
      кладовая (сундук и мимик среди ящиков), вторая шахта и подъёмник,
      тронный зал — логово Живых доспехов. Лестница вниз — за печатью в
      отдельном ходе к востоку от зала.

Свои буквы (легенда — `AreaSpec.legend` в f2.ts):
  m  грибница на полу            g  светящиеся грибы (зелёные)
  i  светящиеся грибы (лиловые)  h  споровая лужа (яд, вязнет)
  w  ручей (глубина)             j  мелководье (вязнет)
  k  мостки над ручьём           q  капель со свода — там живёт слизь
  *  мандрагора в земле          &  мимик (прикидывается сундуком)
  z  хваталка (лиана-хищник)     t  стена с грибами-трутовиками
  f  гриб-великан (лиловый)      F  гриб-великан (зелёный)
  x  дождевики (ломаются)        y  кости и ржавое железо
  r  корни поперёк пола          A  пустые латы на стойке
  I  колонна крепости
"""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from brush import W, Map, check, show, write_floor  # noqa: E402

FLOORISH = '.,'


def scatter(m, cx, cy, rx, ry, c, p, allowed=FLOORISH, keep_path=None):
    """Рассыпать букву по полу внутри овала с вероятностью p."""
    for y in range(int(cy - ry), int(cy + ry) + 1):
        for x in range(int(cx - rx), int(cx + rx) + 1):
            if not m.inb(x, y) or m.lock[y][x]:
                continue
            dx = (x + 0.5 - cx) / rx
            dy = (y + 0.5 - cy) / ry
            if dx * dx + dy * dy > 1:
                continue
            if keep_path and keep_path(x, y):
                continue
            if m.get(x, y) in allowed and m.rng.random() < p:
                m.g[y][x] = c


def fill_if(m, x0, y0, x1, y1, c, allowed=FLOORISH):
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            if m.inb(x, y) and m.get(x, y) in allowed:
                m.g[y][x] = c


def at(m, x, y, c, allowed=FLOORISH + 'mgi'):
    """Поставить предмет на пол ровно здесь (иначе — ошибка: карта уехала)."""
    assert m.get(x, y) in allowed, (x, y, c, m.get(x, y))
    m.put(x, y, c)


def near(m, x, y, c, allowed=FLOORISH + 'mgi'):
    """Поставить на ближайший свободный пол (до двух клеток в сторону)."""
    for r in (0, 1, 2):
        for dy in range(-r, r + 1):
            for dx in range(-r, r + 1):
                if m.get(x + dx, y + dy) in allowed and not m.lock[y + dy][x + dx]:
                    m.put(x + dx, y + dy, c)
                    return
    raise AssertionError(('no floor near', x, y, c))


def wall_mush(m, p=0.22):
    """Трутовики на лице стены: стена, под которой пол."""
    for y in range(1, m.h - 1):
        for x in range(1, W - 1):
            if m.get(x, y) == '#' and not m.lock[y][x] and m.get(x, y + 1) in '.,mgi':
                if m.rng.random() < p:
                    m.g[y][x] = 't'


# ---------------------------------------------------------------------------
# Район 1 — «Грибной грот» (вход). Лифт внизу, выход наверх — столбцы 30–34.
# ---------------------------------------------------------------------------


def grotto():
    H = 136
    m = Map(H, seed=2201, cave='.')

    # Зал лифта: пещера, у лифта светло (две лампы на северной стене).
    m.ell(32, 122, 11, 7)
    m.rect(27, 118, 37, 127)

    # Шахта у лифта: грот к западу, вход в штольню на его северной стене.
    m.ell(14, 123, 6.5, 4.5)
    m.hpath(14, 24, 124, 3)

    # Развилка: на северо-запад — роща, на северо-восток — топи.
    m.hpath(24, 28, 115, 3)
    m.vpath(25, 104, 116, 3)
    m.hpath(37, 41, 115, 3)
    m.vpath(41, 104, 116, 3)

    # Грибная роща: большая пещера с грибами-великанами.
    m.ell(19, 94, 11, 11.5)
    m.ell(25, 102, 5, 4.5)
    # Тупик рощи с настоящим тайником за узким лазом (юго-запад рощи).
    m.vpath(11, 104, 108, 1)
    m.ell(11, 110, 3, 2)

    # Споровые топи: пещера, почти вся в лужах, извилистая сухая тропа.
    m.ell(48, 95, 12, 11)
    m.ell(42, 103, 5, 3.5)

    # Ручей: вытянутый грот поперёк, ручей в середине, мостки.
    m.ell(35, 74, 24, 7, rough=0.16)
    # Роща и топи выходят к ручью.
    m.vpath(17, 79, 84, 3)
    m.vpath(47, 79, 85, 3)

    # Северный берег: тропы сходятся к саду.
    m.vpath(31, 52, 68, 4)
    m.ell(31, 56, 7, 4)

    # Тупик с сундуками: к востоку от берега, извилистый лаз.
    m.hpath(37, 47, 58, 2)
    m.vpath(47, 51, 58, 2)
    m.ell(53, 51, 6.5, 4.5)

    # Сад мандрагор: круглый зал, зал-ловушка.
    m.ell(31, 38, 12, 9)
    # Ходок от шахты к саду: узкий, вдоль западной стены; решётка у сада
    # (открывается из сада — с востока).
    m.vpath(3, 41, 121, 2)
    m.rect(2, 120, 9, 122)
    m.hpath(2, 20, 41, 2)

    # Корневой ход наверх: петляет с нишами хваталок.
    m.vpath(35, 18, 30, 3)
    m.ell(38, 20, 5, 3.5)
    m.hpath(26, 38, 16, 3)
    m.ell(24, 13, 4.5, 3.5)
    m.vpath(26, 4, 12, 3)
    m.hpath(26, 32, 5, 3)
    m.vpath(32, 0, 6, 5)

    # Перемычки, которые дрожь не трогает: ходок отдельно от всего.
    m.protect(4, 42, 7, 119)
    m.protect(8, 110, 20, 117)
    m.protect(4, 36, 16, 39)
    m.jitter(0.28, 2)
    # Решётка — в проходе шириной в клетку: иначе её обходят рядом.
    for x in range(11, 16):
        m.put(x, 40, '#')
    m.put(13, 41, 'D')

    # --- норы по стенам (не у лифта): до украшений — нора ищет голый пол ---
    for x, y in ((27, 85), (29, 90), (59, 92), (36, 99), (12, 71), (58, 73),
                 (40, 60), (19, 36), (43, 38), (30, 29), (20, 13), (43, 21)):
        m.burrow(x, y)

    # --- ручей: две полосы глубины, мелководье по краям, двое мостков ---
    for x in range(9, W - 1):
        for y in (73, 74):
            if m.get(x, y) in '.,':
                m.g[y][x] = 'w'
        for y in (72, 75):
            if m.get(x, y) in '.,' and m.rng.random() < 0.8:
                m.g[y][x] = 'j'
    # Северный край русла — мелководье, чтобы ручей не резал грот «линейкой».
    for x in range(9, W - 1):
        if m.get(x, 71) in '.,' and m.get(x, 72) == 'j' and m.rng.random() < 0.4:
            m.g[71][x] = 'j'
    # Мостки: запад — у выхода из рощи, восток — у выхода из топей.
    for bx in (16, 17, 18, 46, 47, 48):
        for y in (72, 73, 74, 75):
            if m.get(bx, y) in 'wj.,':
                m.put(bx, y, 'k')

    # --- лифт, лампы, шахта ---
    at(m, 32, 123, 'E')
    m.wall_obj(29, 115, 'L')
    m.wall_obj(35, 115, 'L')
    m.wall_obj(13, 118, 'M')

    # Грот начинается у самого лифта: грибница по краям зала, светящиеся
    # грибы, два великана по углам. Площадку лифта не трогаем.
    def lift_pad(x, y):
        return abs(x - 32) < 4 and abs(y - 123) < 4
    scatter(m, 30, 122, 13, 7, 'm', 0.22, keep_path=lift_pad)
    scatter(m, 30, 122, 13, 7, 'g', 0.035, keep_path=lift_pad)
    scatter(m, 30, 122, 13, 7, 'i', 0.03, keep_path=lift_pad)
    near(m, 24, 119, 'F')
    near(m, 40, 126, 'f')
    near(m, 9, 121, 'f')

    # --- роща: великаны, светящиеся грибы, грибница, дождевики ---
    scatter(m, 19, 94, 10, 10.5, 'm', 0.3)
    for x, y, c in ((12, 89, 'f'), (24, 87, 'F'), (14, 100, 'f'), (26, 96, 'f'),
                    (10, 96, 'F'), (20, 103, 'F'), (21, 91, 'f')):
        near(m, x, y, c)
    scatter(m, 19, 94, 10, 10.5, 'g', 0.05)
    scatter(m, 19, 94, 10, 10.5, 'i', 0.04)
    for x, y in ((14, 86), (27, 93), (16, 106), (9, 92)):
        near(m, x, y, 'x')
    near(m, 18, 95, 'R')
    near(m, 11, 111, '$')
    near(m, 9, 110, 'x')
    # Одинокий «сундук» в нише рощи — мимик без настоящего рядом.
    near(m, 27, 105, '&')

    # --- топи: лужи, сухая тропа петлёй, капель над тропой ---
    def trail(x, y):
        # Тропа: от входа снизу (41,104) — на северо-запад, петлёй к выходу.
        t = (abs(x - (43 - (y - 95) * 0.3)) < 1.6 and 88 <= y <= 106) or \
            (abs(y - 89) < 1.3 and 43 <= x <= 55) or \
            (abs(x - 47) < 1.6 and 82 <= y <= 90)
        return t
    scatter(m, 48, 95, 12, 11, 'h', 0.78, keep_path=trail)
    scatter(m, 48, 95, 12, 11, 'i', 0.05, allowed='.')
    for x, y in ((42, 100), (46, 89), (52, 89), (47, 86)):
        near(m, x, y, 'q', allowed='.')
    near(m, 55, 96, 'F', allowed='.,h')
    near(m, 39, 94, 'f', allowed='.,h')

    # --- у ручья: грибница по берегам, хваталки у мостков ---
    scatter(m, 35, 74, 23, 6, 'm', 0.12)
    scatter(m, 35, 74, 23, 6, 'g', 0.04)
    near(m, 21, 70, 'z')
    near(m, 43, 70, 'z')
    near(m, 13, 77, 'F')
    near(m, 55, 77, 'f')
    near(m, 27, 78, 'R')

    # --- северный берег и тупик с сундуками ---
    scatter(m, 31, 56, 6, 3.5, 'm', 0.35)
    near(m, 34, 55, 'q')
    near(m, 51, 50, '$')
    near(m, 54, 49, '&')
    near(m, 56, 52, '&')
    near(m, 53, 54, 'y')
    scatter(m, 53, 51, 5.5, 3.5, 'i', 0.12)

    # --- сад мандрагор: вся земля — грибница, мандрагоры кругом ---
    scatter(m, 31, 38, 11, 8, 'm', 0.6)
    for x, y in ((25, 36), (37, 34), (28, 43), (39, 41), (32, 31)):
        near(m, x, y, '*', allowed='.,m')
    scatter(m, 31, 38, 11, 8, 'g', 0.05)
    scatter(m, 31, 38, 11, 8, 'i', 0.05)
    near(m, 22, 37, 'f')
    near(m, 41, 36, 'F')
    near(m, 31, 39, 'R', allowed='.,m')

    # --- корневой ход: хваталки в нишах, капель, корни ---
    near(m, 41, 20, 'z')
    near(m, 21, 12, 'z')
    near(m, 34, 23, 'q')
    near(m, 29, 16, 'q')
    for y in (8, 27):
        fill_if(m, 24, y, 38, y, 'r')
    scatter(m, 38, 20, 4, 3, 'g', 0.2)
    scatter(m, 24, 13, 4, 3, 'i', 0.2)

    wall_mush(m, 0.2)
    return check(m, 'f2grot')


# ---------------------------------------------------------------------------
# Район 2 — «Заросшие руины». Вход снизу — столбцы 30–34.
# ---------------------------------------------------------------------------


def ruins():
    H = 112
    m = Map(H, seed=2202, cave=',')

    # Сторожка: проход снизу и зал с обвалившимися углами.
    m.vpath(32, 100, 111, 5)
    m.rect(22, 92, 42, 104)
    m.ell(22, 98, 4, 5)
    m.ell(42, 95, 4, 5)

    # Галерея доспехов: длинный зал, колонны в два ряда.
    m.vpath(32, 84, 92, 3)
    m.rect(10, 70, 55, 84)

    # Кладовая (запад): глухая, вход — проём в три клетки.
    m.rect(2, 62, 6, 80)
    m.hpath(6, 10, 77, 3)

    # Подъёмник и вторая шахта (восток), дальше — ход к печати.
    m.rect(58, 64, 62, 80)
    m.hpath(55, 58, 76, 3)

    # Двор мандрагор: провал свода, грунт, северо-западнее галереи.
    m.ell(9, 50, 5.5, 6.5)
    m.vpath(11, 56, 70, 3)

    # Тронный зал (арена): вход с юга через ворота.
    m.rect(19, 19, 47, 40)
    m.vpath(33, 41, 70, 3)
    m.rect(30, 44, 36, 52)

    # Ход к печати: от подъёмника на север, вдоль восточной стены.
    m.vpath(61, 10, 64, 2)
    # Лестница — за печатью, в северо-восточной келье.
    m.rect(52, 3, 61, 10)

    m.protect(48, 11, 59, 42)
    m.protect(14, 14, 18, 44)
    m.protect(7, 60, 9, 75)
    m.protect(56, 60, 57, 74)
    m.jitter(0.25, 2)

    for x, y in ((16, 69), (44, 69), (22, 91), (43, 99), (3, 72), (14, 48), (32, 60)):
        m.burrow(x, y)

    # --- арена: закрыта, выход — только ворота (3 клетки) ---
    for x in range(32, 35):
        m.put(x, 41, 'G')
    at(m, 33, 31, 'K')
    for x, y in ((25, 24), (41, 24), (25, 36), (41, 36)):
        at(m, x, y, 'I')
    m.wall_obj(26, 18, 'L')
    m.wall_obj(40, 18, 'L')
    scatter(m, 33, 30, 13, 10, 'i', 0.03, allowed='.,')
    scatter(m, 33, 30, 14, 11, ',', 0.25, allowed='.')
    scatter(m, 33, 30, 14, 11, 'm', 0.12)
    scatter(m, 33, 30, 14, 11, 'y', 0.03, allowed='.')
    at(m, 35, 44, 'T')
    m.wall_obj(30, 43, 'L')
    m.wall_obj(36, 43, 'L')

    # --- печать и лестница ---
    for x in (60, 61):
        m.put(x, 30, 'S')
    at(m, 56, 6, '>')
    m.wall_obj(56, 2, 'L')

    # --- галерея: колонны, латы на стойках, кости, грибница по плитам ---
    for x in range(15, 55, 8):
        at(m, x, 73, 'I')
        at(m, x, 81, 'I')
    for x in (12, 20, 28, 38, 46, 53):
        near(m, x, 71, 'A')
    scatter(m, 32, 77, 23, 7, ',', 0.2, allowed='.')
    scatter(m, 32, 77, 23, 7, 'm', 0.14)
    scatter(m, 32, 77, 23, 7, 'y', 0.03, allowed='.')
    scatter(m, 32, 77, 23, 7, 'g', 0.02)
    near(m, 24, 78, 'u')
    near(m, 42, 76, 'u')
    near(m, 32, 77, 'R')
    near(m, 20, 83, 'q')
    near(m, 46, 83, 'q')
    m.wall_obj(28, 69, 'M')

    # --- кладовая: ящики, бочки, тайник и мимик среди них ---
    for x, y, c in ((3, 63, 'C'), (4, 63, 'C'), (6, 64, 'B'), (3, 70, 'B'),
                    (6, 72, 'C'), (3, 79, 'C'), (5, 79, 'B')):
        near(m, x, y, c)
    near(m, 4, 66, '$')
    near(m, 3, 67, '&')
    near(m, 5, 75, 'y')

    # --- подъёмник руин (чинится) ---
    at(m, 60, 72, 'E')
    near(m, 59, 79, 'C')

    # --- двор мандрагор ---
    scatter(m, 9, 50, 5, 6, 'm', 0.6, allowed='.,')
    near(m, 7, 47, '*', allowed='.,m')
    near(m, 11, 52, '*', allowed='.,m')
    near(m, 8, 55, 'F')
    scatter(m, 9, 50, 5, 6, 'i', 0.08)
    near(m, 9, 45, '$')

    # --- сторожка: грибница, капель, хваталка у прохода ---
    scatter(m, 32, 98, 10, 6, ',', 0.35, allowed='.')
    scatter(m, 32, 98, 10, 6, 'm', 0.25)
    near(m, 26, 95, 'z')
    near(m, 38, 101, 'q')
    near(m, 24, 101, 'f')
    near(m, 41, 93, 'F')
    near(m, 33, 88, 'q')

    wall_mush(m, 0.12)
    return check(m, 'f2ruin')


def main():
    g = grotto()
    r = ruins()
    # Стык районов: нижний ряд руин и верхний ряд грота — проход в тех же
    # столбцах.
    gap_top = [x for x in range(W) if g[0][x] != '#']
    gap_bot = [x for x in range(W) if r[-1][x] != '#']
    assert set(gap_top) == set(gap_bot), (gap_top, gap_bot)
    if '--show' in sys.argv:
        show(r, 'R ')
        show(g, 'G ')
        return
    write_floor(2, {'MAP_F2_GROT': g, 'MAP_F2_RUIN': r})


if __name__ == '__main__':
    main()
