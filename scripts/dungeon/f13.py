def find(rows, ch):
    return [(x, y) for y, r in enumerate(rows) for x, c in enumerate(r) if c == ch]


def bfs(rows, sx, sy, ok):
    h = len(rows)
    seen = [[False] * W for _ in range(h)]
    q = deque([(sx, sy)])
    seen[sy][sx] = True
    while q:
        x, y = q.popleft()
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            nx, ny = x + dx, y + dy
            if 0 <= nx < W and 0 <= ny < h and not seen[ny][nx] and ok(rows[ny][nx]):
                seen[ny][nx] = True
                q.append((nx, ny))
    return seen


def verify(areas):
    world = []
    for rows in reversed(areas):
        world += rows
    lift = find(areas[0], 'E')[0]
    top0 = len(world) - len(areas[0])
    lx, ly = lift[0], lift[1] + top0
    walkable = lambda c: c in PASS or c == 'S'
    sealed = lambda c: c in PASS
    seen = bfs(world, lx, ly, walkable)
    closed = bfs(world, lx, ly, sealed)
    k = find(world, 'K')[0]
    assert seen[k[1]][k[0]], 'босс недостижим'
    for (x, y) in find(world, 'M'):
        assert seen[y + 1][x], ('шахта недостижима', x, y)
    for (x, y) in find(world, '>'):
        assert seen[y][x], 'лестница недостижима с открытой печатью'
        assert not closed[y][x], 'к лестнице можно пройти мимо печати'
    arena_walk = lambda c: c in PASS and c not in 'GDS%'
    arena = bfs(world, k[0], k[1], arena_walk)
    n = sum(1 for r in arena for v in r if v)
    assert 40 < n < 1500, ('площадь арены', n)
    assert not arena[ly][lx], 'лифт внутри арены'
    for (x, y) in find(world, '>'):
        assert not arena[y][x], 'лестница внутри арены'
    for (x, y) in find(world, 'T'):
        d = ((x - k[0]) ** 2 + (y - k[1]) ** 2) ** 0.5
        assert d <= 14, ('табличка логова далеко', d)
    # Пол, до которого не дойти ногами, — только островки крюков.
    lost = [(x, y) for y, r in enumerate(world) for x, c in enumerate(r)
            if c in PASS and not seen[y][x]]
    # Островки: каждый обязан иметь кольцо крюка (куда выносит).
    groups = []
    left = set(lost)
    while left:
        x, y = left.pop()
        g = {(x, y)}
        q = [(x, y)]
        while q:
            cx, cy = q.pop()
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                c = (cx + dx, cy + dy)
                if c in left:
                    left.discard(c)
                    g.add(c)
                    q.append(c)
        groups.append(g)
    for g in groups:
        assert any(world[y][x] == '^' for (x, y) in g), ('недостижимый пол без крюка', sorted(g)[:6])
        assert any(world[y][x] == '0' for (x, y) in g), ('островок без столба обратно', sorted(g)[:6])
    print(f'  арена {n} клеток, мир {len(world)} рядов, островков {len(groups)}', file=sys.stderr)


def verify_hooks(m, rows, name):
    """Каждый столб выносит за преграду (провал или стену), не дальше 13 клеток."""
    posts = set(find(rows, '0'))
    for (x, y, tx, ty) in m.hooks:
        assert (x, y) in posts, (name, 'столб затёрт', x, y)
        assert rows[ty][tx] == '^', (name, 'кольцо затёрто', tx, ty)
        d = ((tx - x) ** 2 + (ty - y) ** 2) ** 0.5
        assert 2 <= d <= 13, (name, 'длина крюка', x, y, d)
        n = int(d * 3) + 1
        crosses = any(rows[int(y + 0.5 + (ty - y) * i / n)][int(x + 0.5 + (tx - x) * i / n)] not in PASS
                      for i in range(1, n))
        assert crosses, (name, 'крюк не через преграду', x, y, tx, ty)
    assert len(posts) == len(m.hooks), (name, 'столб без пары', posts - {(a, b) for a, b, _, _ in m.hooks})


