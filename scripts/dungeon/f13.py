def rect(m, x0, y0, x1, y1, ch):
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            if m.inb(x, y):
                m.g[y][x] = ch


def paint(m, x0, y0, x1, y1, ch, share=1.0, ok='.'):
    rng = m.rng
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            if 0 <= y < m.h and 0 < x < W - 1 and m.g[y][x] in ok and not m.lock[y][x]:
                if rng.random() < share:
                    m.g[y][x] = ch


def speckle(m, x0, y0, x1, y1, ch, n, ok='.', gap=2):
    rng = m.rng
    cells = [(x, y) for y in range(y0, y1 + 1) for x in range(x0, x1 + 1)
             if 0 <= y < m.h and 0 < x < W - 1 and m.g[y][x] in ok and not m.lock[y][x]]
    rng.shuffle(cells)
    placed = []
    for (x, y) in cells:
        if len(placed) >= n:
            break
        if any(abs(x - a) + abs(y - b) < gap for a, b in placed):
            continue
        m.g[y][x] = ch
        placed.append((x, y))
    return placed


def faces(m, x0, y0, x1, y1, ok=FLOORS):
    """Стены с полом под ними (фасады) в прямоугольнике."""
    out = []
    for y in range(max(0, y0), min(m.h - 1, y1 + 1)):
        for x in range(max(1, x0), min(W - 1, x1 + 1)):
            if m.g[y][x] == '#' and m.g[y + 1][x] in ok and not m.lock[y][x]:
                out.append((x, y))
    return out


def roofs(m, x0, y0, x1, y1):
    """Крыши: стены, под которыми тоже стена (не фасад)."""
    out = []
    for y in range(max(1, y0), min(m.h - 1, y1 + 1)):
        for x in range(max(1, x0), min(W - 1, x1 + 1)):
            if m.g[y][x] == '#' and m.g[y + 1][x] in '#QAJ' and not m.lock[y][x]:
                out.append((x, y))
    return out


def dress_facades(m, x0, y0, x1, y1, shops=0, windows=0, torches=0):
    rng = m.rng
    fc = faces(m, x0, y0, x1, y1)
    rng.shuffle(fc)
    k = 0
    for (x, y) in fc:
        if k < shops:
            m.put(x, y, '[')
        elif k < shops + windows:
            m.put(x, y, ']')
        elif k < shops + windows + torches:
            m.put(x, y, 'U')
        else:
            break
        k += 1


def dress_roofs(m, x0, y0, x1, y1, chimneys=0, burnt=0, fires=0):
    rng = m.rng
    rf = roofs(m, x0, y0, x1, y1)
    rng.shuffle(rf)
    placed = []
    for (x, y) in rf:
        if len(placed) >= chimneys:
            break
        if any(abs(x - a) + abs(y - b) < 4 for a, b in placed):
            continue
        m.put(x, y, 'J')
        placed.append((x, y))
    rf = roofs(m, x0, y0, x1, y1)
    rng.shuffle(rf)
    for (x, y) in rf[:burnt]:
        m.g[y][x] = 'Q'
    rf = [c for c in roofs(m, x0, y0, x1, y1)]
    rng.shuffle(rf)
    placed = []
    for (x, y) in rf:
        if len(placed) >= fires:
            break
        if any(abs(x - a) + abs(y - b) < 5 for a, b in placed):
            continue
        m.put(x, y, 'A')
        placed.append((x, y))


def hole(m, x, y):
    """Пролом в стене дома, откуда лезут ухмылки: стена, рядом пол."""
    def ok(x, y):
        return (m.get(x, y) in '#Q' and not m.lock[y][x] and 1 < x < W - 2 and any(
            m.get(x + dx, y + dy) in FLOORS for dx, dy in ((0, 1), (1, 0), (-1, 0), (0, -1))))
    if ok(x, y):
        m.put(x, y, 'o')
        return
    for r in range(1, 6):
        for dx, dy in ((-r, 0), (r, 0), (0, -r), (0, r)):
            if ok(x + dx, y + dy):
                print(f'  сдвиг o ({x},{y}) -> ({x+dx},{y+dy})', file=sys.stderr)
                m.put(x + dx, y + dy, 'o')
                return
    print(f'  НЕТ МЕСТА для норы ({x},{y})', file=sys.stderr)


def hook(m, x, y, tx, ty):
    """Столб-якорь в (x, y) и кольцо, куда он выносит, в (tx, ty)."""
    if not hasattr(m, 'hooks'):
        m.hooks = []
    assert m.g[y][x] in FLOORS + OBJS, ('столб не на полу', x, y, m.g[y][x])
    assert m.g[ty][tx] in FLOORS + OBJS, ('кольцо не на полу', tx, ty, m.g[ty][tx])
    m.put(x, y, '0')
    m.put(tx, ty, '^')
    m.hooks.append((x, y, tx, ty))


def wall_obj(m, x, y, c):
    """Настенное (шахта, лампа): стена, под ней пол."""
    assert m.g[y][x] in WALLISH, ('not wall', x, y, c, m.g[y][x])
    assert m.g[y + 1][x] in FLOORS, ('no floor below', x, y, c, m.g[y + 1][x])
    m.put(x, y, c)


def rough(m, x0, y0, x1, y1, ch, k=0.0, edge=1):
    """Провал с рваными краями: край гуляет на клетку по синусам."""
    import math
    for y in range(y0, y1 + 1):
        a = int(round(math.sin(y * 0.7 + k) * 0.8 + math.sin(y * 0.31 + 1.7 + k) * 0.5)) * edge
        b = int(round(math.sin(y * 0.53 + 2.1 + k) * 0.8 + math.sin(y * 0.23 + k) * 0.5)) * edge
        for x in range(x0 + max(0, a), x1 - max(0, b) + 1):
            if m.inb(x, y) and not m.lock[y][x]:
                m.g[y][x] = ch


def rough_h(m, x0, y0, x1, y1, ch, k=0.0):
    """Провал поперёк улицы: рвутся верхний и нижний край."""
    import math
    for x in range(x0, x1 + 1):
        a = int(round(math.sin(x * 0.61 + k) * 0.7 + math.sin(x * 0.27 + 2.3 + k) * 0.6))
        b = int(round(math.sin(x * 0.47 + 1.1 + k) * 0.7 + math.sin(x * 0.19 + k) * 0.6))
        for y in range(y0 + max(0, a), y1 - max(0, b) + 1):
            if m.inb(x, y) and not m.lock[y][x]:
                m.g[y][x] = ch


