# Клетки, на которых стоят (для настенного и нор).
FLOORISH = '.,mptexkjqwyzrf0123456789AHJNOUVW[]}F(*Z+<^&?{-/'


def paint(m, x0, y0, x1, y1, ch, share=1.0, ok='.'):
    rng = m.rng
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            if 0 <= y < m.h and 0 < x < W - 1 and m.g[y][x] in ok and not m.lock[y][x]:
                if rng.random() < share:
                    m.g[y][x] = ch


def speckle(m, x0, y0, x1, y1, ch, n, ok='.', gap=2):
    """Раскидать `n` клеток `ch` по полу прямоугольника, не ближе `gap`."""
    rng = m.rng
    cells = [(x, y) for y in range(y0, y1 + 1) for x in range(x0, x1 + 1)
             if 0 <= y < m.h and 0 < x < W - 1 and m.g[y][x] in ok and not m.lock[y][x]]
    rng.shuffle(cells)
    placed = []
    for (x, y) in cells:
        if len(placed) >= n:
            break
        if any(abs(x - a) + abs(y - b) < gap for a, b in placed):
            continue
        m.put(x, y, ch)
        placed.append((x, y))
    return placed


def disc(m, cx, cy, r, ch, ok=None):
    """Круг клеток (центр клетки ближе r к точке cx, cy)."""
    out = []
    for y in range(int(cy - r) - 1, int(cy + r) + 2):
        for x in range(int(cx - r) - 1, int(cx + r) + 2):
            if not m.inb(x, y):
                continue
            if math.hypot(x + 0.5 - cx, y + 0.5 - cy) <= r:
                if ok is None or m.g[y][x] in ok:
                    m.g[y][x] = ch
                    out.append((x, y))
    return out


def hole(m, x, y):
    """Дверца, откуда выходят куклы: стена, рядом пол любого вида."""
    def ok(x, y):
        return (m.get(x, y) == '#' and not m.lock[y][x] and 0 < x < W - 1 and any(
            m.get(x + dx, y + dy) in FLOORISH for dx, dy in ((0, 1), (1, 0), (-1, 0), (0, -1))))
    if ok(x, y):
        m.put(x, y, 'o')
        return
    for r in range(1, 6):
        for dx, dy in ((-r, 0), (r, 0), (0, -r), (0, r)):
            if ok(x + dx, y + dy):
                print(f'  сдвиг o ({x},{y}) -> ({x+dx},{y+dy})', file=sys.stderr)
                m.put(x + dx, y + dy, 'o')
                return
    raise SystemExit(f'НЕТ места для дверцы ({x},{y})')


def face(m, x, y, c):
    """Настенное: стена, под ней пол. Мимо — ищем рядом по ряду."""
    for dx in (0, 1, -1, 2, -2, 3, -3):
        xx = x + dx
        if (m.get(xx, y) == '#' and m.get(xx, y + 1) in FLOORISH and not m.lock[y][xx]):
            if dx:
                print(f'  сдвиг {c} ({x},{y}) -> ({xx},{y})', file=sys.stderr)
            m.put(xx, y, c)
            return
    raise SystemExit(f'НЕТ стены для {c} ({x},{y})')


def walls_around(m, x0, y0, x1, y1):
    """Сплошная стена по контуру прямоугольника (и защита от дрожи)."""
    for x in range(x0, x1 + 1):
        m.set(x, y0, '#')
        m.set(x, y1, '#')
    for y in range(y0, y1 + 1):
        m.set(x0, y, '#')
        m.set(x1, y, '#')
    m.protect(x0, y0, x1, y1)


def post(m, x, y, c):
    """Пост монстра: клетка пола с цифрой."""
    assert m.g[y][x] in FLOORISH, (x, y, c, m.g[y][x])
    m.put(x, y, c)


def trap(m, x, y, out):
    """Люк 2×2 (левый верхний угол x, y)."""
    cells = []
    for yy in (y, y + 1):
        for xx in (x, x + 1):
            m.put(xx, yy, 'z')
            cells.append([xx, yy])
    out.append(cells)


def cells_of(m, x0, y0, x1, y1, ok):
    return [[x, y] for y in range(y0, y1 + 1) for x in range(x0, x1 + 1) if m.g[y][x] in ok]


