def carve(m, x, y, c='.', natural=True):
    if m.inb(x, y) and not m.lock[y][x]:
        m.g[y][x] = c
        m.natural[y][x] = natural


def disc(m, cx, cy, r, c='.', natural=True):
    for y in range(int(cy - r) - 1, int(cy + r) + 2):
        for x in range(int(cx - r) - 1, int(cx + r) + 2):
            if (x + 0.5 - cx) ** 2 + (y + 0.5 - cy) ** 2 <= r * r:
                carve(m, x, y, c, natural)


def tube(m, pts, r, c='.', wobble=0.25, seed=0.0):
    """Ход по кривой через точки: диски вдоль сплайна, радиус гуляет."""
    def cr(p0, p1, p2, p3, t):
        t2, t3 = t * t, t * t * t
        return 0.5 * (2 * p1 + (-p0 + p2) * t + (2 * p0 - 5 * p1 + 4 * p2 - p3) * t2
                      + (-p0 + 3 * p1 - 3 * p2 + p3) * t3)
    for i in range(len(pts) - 1):
        p0 = pts[max(0, i - 1)]
        p1 = pts[i]
        p2 = pts[i + 1]
        p3 = pts[min(len(pts) - 1, i + 2)]
        n = int(max(abs(p2[0] - p1[0]), abs(p2[1] - p1[1])) * 3) + 2
        for k in range(n):
            t = k / n
            x = cr(p0[0], p1[0], p2[0], p3[0], t)
            y = cr(p0[1], p1[1], p2[1], p3[1], t)
            rr = r * (1 + wobble * math.sin((i * n + k) * 0.37 + seed))
            disc(m, x, y, rr, c)
    disc(m, pts[-1][0], pts[-1][1], r, c)


def paint(m, x0, y0, x1, y1, ch, share=1.0, ok='.'):
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            if 0 <= y < m.h and 0 < x < W - 1 and m.g[y][x] in ok and not m.lock[y][x]:
                if m.rng.random() < share:
                    m.g[y][x] = ch


def speckle(m, x0, y0, x1, y1, ch, n, ok=PLAIN, gap=2, lock=True, clear=0):
    """Раскидать `n` клеток `ch` по полу прямоугольника, не ближе `gap`.
    `clear` — сколько клеток пола вокруг обязано быть (предмет не затыкает ход)."""
    rng = m.rng
    cells = [(x, y) for y in range(y0, y1 + 1) for x in range(x0, x1 + 1)
             if 0 <= y < m.h and 0 < x < W - 1 and m.g[y][x] in ok and not m.lock[y][x]]
    rng.shuffle(cells)
    placed = []
    for (x, y) in cells:
        if len(placed) >= n:
            break
        if any(abs(x - a) + abs(y - b) < gap for a, b in placed):
            continue
        if clear:
            around = sum(1 for dx in (-1, 0, 1) for dy in (-1, 0, 1)
                         if m.get(x + dx, y + dy) in FLOORISH)
            if around < 9 - (3 - clear):
                continue
        m.g[y][x] = ch
        if lock:
            m.lock[y][x] = True
        placed.append((x, y))
    return placed


def faces(m, x0, y0, x1, y1, ok=FLOORISH):
    """Клетки стены, под которыми пол: лицо стены видно."""
    out = []
    for y in range(max(0, y0), min(m.h - 1, y1 + 1)):
        for x in range(max(1, x0), min(W - 1, x1 + 1)):
            if m.g[y][x] == '#' and m.g[y + 1][x] in ok and not m.lock[y][x]:
                out.append((x, y))
    return out


def on_faces(m, x0, y0, x1, y1, ch, n, gap=3):
    cells = faces(m, x0, y0, x1, y1)
    m.rng.shuffle(cells)
    placed = []
    for (x, y) in cells:
        if len(placed) >= n:
            break
        if any(abs(x - a) + abs(y - b) < gap for a, b in placed):
            continue
        m.put(x, y, ch)
        placed.append((x, y))
    return placed


def put_face(m, x, y, c):
    """Настенное: стена, под ней пол. Мимо — ищем рядом."""
    def ok(x, y):
        return m.get(x, y) == '#' and m.get(x, y + 1) in FLOORISH and not m.lock[y][x]
    if ok(x, y):
        m.put(x, y, c)
        return (x, y)
    for r in (1, 2, 3):
        for dy in (0, -1, 1, -2, 2):
            for dx in range(-r, r + 1):
                if ok(x + dx, y + dy):
                    m.put(x + dx, y + dy, c)
                    return (x + dx, y + dy)
    raise AssertionError(('no wall face', x, y, c))


def hole(m, x, y):
    """Пора в мышце: стена, рядом пол любого вида."""
    def ok(x, y):
        return (m.get(x, y) == '#' and not m.lock[y][x] and 0 < x < W - 1 and any(
            m.get(x + dx, y + dy) in FLOORISH for dx, dy in ((0, 1), (1, 0), (-1, 0), (0, -1))))
    if ok(x, y):
        m.put(x, y, 'o')
        return
    for r in range(1, 6):
        for dx, dy in ((-r, 0), (r, 0), (0, -r), (0, r)):
            if ok(x + dx, y + dy):
                m.put(x + dx, y + dy, 'o')
                return
    print('  нет места для поры', x, y, file=sys.stderr)


def at(m, x, y, c, ok=FLOORISH):
    """Предмет или пол строго в клетку (с поиском рядом)."""
    if m.get(x, y) in ok and not m.lock[y][x]:
        m.put(x, y, c)
        return (x, y)
    for r in (1, 2):
        for dy in range(-r, r + 1):
            for dx in range(-r, r + 1):
                if m.get(x + dx, y + dy) in ok and not m.lock[y + dy][x + dx]:
                    m.put(x + dx, y + dy, c)
                    return (x + dx, y + dy)
    raise AssertionError(('no floor near', x, y, c))


def vein(m, pts, c='y'):
    """Вена по полу: ломаная через точки, только по плоти."""
    for i in range(len(pts) - 1):
        (x0, y0), (x1, y1) = pts[i], pts[i + 1]
        n = max(abs(x1 - x0), abs(y1 - y0), 1)
        for k in range(n + 1):
            x = round(x0 + (x1 - x0) * k / n)
            y = round(y0 + (y1 - y0) * k / n)
            if m.get(x, y) in '.ekdz' and not m.lock[y][x]:
                m.g[y][x] = c


def ring_rows(m, x0, x1, y0, y1, step=4, c='r'):
    """Хрящевые кольца поперёк хода."""
    for y in range(y0, y1 + 1, step):
        for x in range(x0, x1 + 1):
            if m.g[y][x] == '.':
                m.g[y][x] = c


SPOTS = []


def spot(kind, area, x, y, *rest):
    SPOTS.append(' '.join([kind, area, str(x), str(y)] + [str(r) for r in rest]))




def box(m, x0, y0, x1, y1, c='#'):
    """Залить прямоугольник (стена по умолчанию) — вернуть перемычку."""
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            if m.inb(x, y):
                m.g[y][x] = c
                m.lock[y][x] = c == '#'


