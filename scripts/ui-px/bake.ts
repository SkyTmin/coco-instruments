// Pixel UI kit — bake. Rules: `.claude/rules/ui-px.md`.
//
//   npx vite-node scripts/ui-px/bake.ts
//
// 1. Draws every piece of `src/ui-px/paint.ts` (pure TS, deterministic).
// 2. Measures each 9-slice from the pixels (`measureSlice`) and FAILS if the declared slice
//    differs — a slice that cuts into the kant smears it into the middle (game-ui.md).
// 3. Writes `public/ui/kit/<name>.png` (RGBA PNG, own encoder) and `src/ui-px/kit.gen.css`
//    (one class per piece: source with `?v=<sha1>`, slice, width in `--u` art pixels, repeat).

import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { measureSlice, PIECES } from '../../src/ui-px/paint';
import type { Pix } from '../../src/ui-px/paint';

const HERE = path.dirname(new URL(import.meta.url).pathname);
const ROOT = path.join(HERE, '..', '..');
const OUT = path.join(ROOT, 'public', 'ui', 'kit');
const CSS = path.join(ROOT, 'src', 'ui-px', 'kit.gen.css');

const CRC = new Uint32Array(256).map((_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});
function crc32(b: Buffer): number {
  let c = 0xffffffff;
  for (const x of b) c = CRC[(c ^ x) & 255] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}
function chunk(type: string, data: Buffer): Buffer {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length);
  const td = Buffer.concat([Buffer.from(type, 'ascii'), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(td));
  return Buffer.concat([len, td, crc]);
}
function png(p: Pix): Buffer {
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(p.w, 0);
  ihdr.writeUInt32BE(p.h, 4);
  ihdr[8] = 8; // bit depth
  ihdr[9] = 6; // RGBA
  const raw = Buffer.alloc((p.w * 4 + 1) * p.h);
  for (let y = 0; y < p.h; y++) {
    raw[y * (p.w * 4 + 1)] = 0;
    Buffer.from(p.data.buffer, y * p.w * 4, p.w * 4).copy(raw, y * (p.w * 4 + 1) + 1);
  }
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', ihdr),
    chunk('IDAT', zlib.deflateSync(raw, { level: 9 })),
    chunk('IEND', Buffer.alloc(0)),
  ]);
}

fs.mkdirSync(OUT, { recursive: true });
for (const f of fs.readdirSync(OUT)) if (f.endsWith('.png')) fs.rmSync(path.join(OUT, f));

const css: string[] = [
  '/* Generated by scripts/ui-px/bake.ts from src/ui-px/paint.ts — do not edit by hand. */',
];
const root: string[] = [];
let bytes = 0;
const bad: string[] = [];
for (const piece of PIECES) {
  const p = piece.draw();
  const buf = png(p);
  bytes += buf.length;
  fs.writeFileSync(path.join(OUT, `${piece.name}.png`), buf);
  const v = crypto.createHash('sha1').update(buf).digest('hex').slice(0, 8);
  const url = `url('/ui/kit/${piece.name}.png?v=${v}')`;
  if (piece.kind === 'frame') {
    const rep = piece.repeat ?? 'stretch';
    const m = measureSlice(p, rep, piece.fixedH);
    const d = piece.slice ?? m;
    if (m.join() !== d.join())
      bad.push(`${piece.name}: declared ${d.join(' ')}, pixels say ${m.join(' ')}`);
    // Widths are NUMBERS: multiples of the element's border-width, which the kit sets to one art
    // pixel (`border: var(--u) solid transparent`) — the frame follows `--ui-scale` wherever set.
    root.push(
      `  --pxk-${piece.name}: ${url};\n  --pxk-${piece.name}-s: ${m.join(' ')}${piece.fill ? ' fill' : ''};\n` +
        `  --pxk-${piece.name}-w: ${m.join(' ')};`,
    );
    css.push(
      `.pxk-${piece.name} {\n  border-image-source: var(--pxk-${piece.name});\n` +
        `  border-image-slice: var(--pxk-${piece.name}-s);\n  border-image-width: var(--pxk-${piece.name}-w);\n` +
        `  border-image-repeat: ${rep};\n}`,
    );
    // Without the centre (`fill` paints over the background): stages show their floor tile.
    if (piece.fill)
      css.push(`.pxk-${piece.name}.px-nofill {\n  border-image-slice: ${m.join(' ')};\n}`);
  } else if (piece.kind === 'icon') {
    css.push(
      `.pxi-${piece.name.slice(2)} {\n  -webkit-mask-image: ${url};\n  mask-image: ${url};\n  --i-w: ${p.w};\n  --i-h: ${p.h};\n}`,
    );
  } else if (piece.kind === 'tile') {
    css.push(
      `.pxt-${piece.name.slice(5)} {\n  --tile: ${url};\n  --tile-w: ${p.w};\n  --tile-h: ${p.h};\n}`,
    );
  } else {
    root.push(
      `  --pximg-${piece.name}: ${url};\n  --pximg-${piece.name}-w: ${p.w};\n  --pximg-${piece.name}-h: ${p.h};`,
    );
  }
}
if (bad.length) {
  console.error(bad.join('\n'));
  process.exit(1);
}
// Buttons: one block per variant and state (the frame of a state = 3 vars, picked by `.px-btn`).
const vars = (n: string) =>
  `--b: var(--pxk-${n});\n  --bs: var(--pxk-${n}-s);\n  --bw: var(--pxk-${n}-w);`;
for (const m of ['gold', 'iron', 'red', 'green']) {
  css.push(
    `.px-btn--${m} {\n  ${vars(`btn-${m}-n`)}\n}`,
    `@media (hover: hover) and (pointer: fine) {\n  .px-btn--${m}:hover {\n    ${vars(`btn-${m}-h`).replace(/\n {2}/g, '\n    ')}\n  }\n}`,
    `.px-btn--${m}:active,\n.px-btn--${m}.is-down {\n  ${vars(`btn-${m}-p`)}\n}`,
    `.px-btn--${m}[aria-disabled='true'] {\n  ${vars(`btn-${m}-d`)}\n}`,
  );
}
// Item cells by rarity.
for (const piece of PIECES.filter((x) => x.name.startsWith('slot-r')))
  css.push(`.px-slot--${piece.name.slice(5)} {\n  ${vars(piece.name)}\n}`);
css.splice(1, 0, `:root {\n${root.join('\n')}\n}`);
fs.writeFileSync(CSS, css.join('\n\n') + '\n');
console.log(
  `ui-px: ${PIECES.length} pieces, ${(bytes / 1024).toFixed(1)} KB → public/ui/kit/, kit.gen.css`,
);
