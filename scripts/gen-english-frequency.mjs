// Generates src/lib/english-frequency.ts from the public google-10000-english
// frequency list, minus function words and the curated core (english-words.ts).
//
// One-off dev tool — run in a networked environment, or pass a pre-downloaded
// list file:
//   curl -s https://raw.githubusercontent.com/first20hours/google-10000-english/master/google-10000-english-no-swears.txt -o /tmp/freq.txt
//   node scripts/gen-english-frequency.mjs /tmp/freq.txt
//
// The output is committed; the app never fetches the list at runtime.

/* global process, fetch, console */
import { readFileSync, writeFileSync } from 'node:fs';

const SRC =
  'https://raw.githubusercontent.com/first20hours/google-10000-english/master/google-10000-english-no-swears.txt';
const LIMIT = 2500;

// Grammatical "glue" words — useless as vocabulary flash-cards, so they're cut.
const STOP = new Set(
  `a an the i you he she it we they me him her us them my your his its our their mine yours hers ours theirs
   this that these those who whom whose which what myself yourself himself herself itself ourselves yourselves themselves
   am is are was were be been being do does did done have has had having get got
   will would shall should can could may might must ought need
   of to in for on with at by from up about into over under below as than
   and or but nor so yet if then else because while where when how why although though since until unless whether
   not no nor yes very too also just only even well there here out off down all any some each every both more most
   other such own same again ever never always now new also like one two three four five six seven eight nine ten
   am pm etc www com org net http https`
    .split(/\s+/)
    .filter(Boolean),
);

const core = new Set(
  [...readFileSync('src/lib/english-words.ts', 'utf8').matchAll(/word:\s*'([a-z]+)'/g)].map(
    (m) => m[1],
  ),
);

async function loadList() {
  const arg = process.argv[2];
  if (arg) return readFileSync(arg, 'utf8');
  const res = await fetch(SRC);
  if (!res.ok) throw new Error(`fetch failed: ${res.status}`);
  return res.text();
}

const text = await loadList();
const words = [];
const seen = new Set();
for (const raw of text.split(/\r?\n/)) {
  const w = raw.trim().toLowerCase();
  if (!/^[a-z]{3,}$/.test(w)) continue; // letters only, length ≥ 3
  if (STOP.has(w) || core.has(w) || seen.has(w)) continue;
  seen.add(w);
  words.push(w);
  if (words.length >= LIMIT) break;
}

const body = `// AUTO-GENERATED by scripts/gen-english-frequency.mjs — do not edit by hand.
//
// English words in rough frequency order (most common first), with grammatical
// function words and the curated core (english-words.ts) removed. Source: the
// public-domain google-10000-english list (Google Trillion Word Corpus n-grams).
//
// This is the never-ending queue that continues after the curated deck. The
// translation and Russian reading for these words are fetched on-device and
// cached (see english-deck.ts), so this file is just the ordered word list.

export const ENGLISH_FREQUENCY: readonly string[] = [
${words.map((w) => `  '${w}',`).join('\n')}
];
`;

writeFileSync('src/lib/english-frequency.ts', body);
console.log(`wrote src/lib/english-frequency.ts with ${words.length} words`);
