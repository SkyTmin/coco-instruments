/** Номер вида клетки круга пары k (1…9). */
export const ringMark = (k: number) => F9_MARK.ring + k;
/** Круг ли это (любой: пара, ловушка, выход). */
export const isRingMark = (mk: number) => mk > F9_MARK.ring && mk <= F9_MARK.back;
/** Вода топи (с кувшинками — тоже вода). */
export const isWaterMark = (mk: number) =>
  mk === F9_MARK.water || mk === F9_MARK.lily || mk === F9_MARK.sunk;
/** Трясина (с камышом и икрой — тоже). */
export const isBogMark = (mk: number) =>
  mk === F9_MARK.bog || mk === F9_MARK.reeds || mk === F9_MARK.eggs || mk === F9_MARK.flood;

