// Этаж 9 — «Лабиринт гидры». Затопленные руины, болото и корни, круги-
// телепорты, которые переносят в пару (пара — по цвету и руне; часть кругов
// — ловушки), а в чёрной заводи на дне — многоглавая гидра.
//
// Монстры и их приём (ИИ — `f9-brains.ts`, рисунок — `f9-art.ts`):
//   • ящеролюд-копейщик — держит дистанцию копья, выпад по линии; в трясине
//     не вязнет, а бежит быстрее;
//   • ядовитая жаба — плевок навесом, на месте падения — лужа яда; сидя в
//     ядовитой топи, плюётся очередью;
//   • телепорт-кобольд — прыгает за спину (короткая метка), убегает прыжком;
//     ходит кругами-телепортами, как ты;
//   • каменный змей — взгляд конусом: замедляет, второй взгляд подряд —
//     каменеешь (оглушение); за стеной не достанет;
//   • болотный огонь — светится и заманивает к воде, вспыхивает холодом;
//   • корневая хваталка — живёт только в трясине: под водой невидима,
//     вокруг героя — круг корней (держат), потом открыта и хлещет;
//   • пиявка — выпрыгивает из воды, присасывается (пьёт кровь), рывок
//     стряхивает;
//   • ящер-жрец — рисует под героем руну: не вышел — перенесён к жрецу, в
//     кольцо ящеров;
//   • кобольд-скупщик — редкий, с мешком монет: убегает кругами и прыжками.
// Босс — многоглавая гидра (`f9boss`, тело) с головами-частями (`f9_head`)
// и скрытой головой (`f9_crown`); срубленная голова отрастает двумя, если
// шею не прижечь огнём жаровни (`f9_stump`). Правила этажа — круги,
// корневая часовня, круговорот, прилив на гати — `registerFloor(9)`.
//
// Карта — `scripts/dungeon/f9.py` → `f9-map.ts` (руками не править).

