// Этаж 15 «Ядро подземелья» — половина агента «Сердце»: верхний район «Ядро»
// (Зал памяти и арена вокруг упавшей звезды), финальный босс всей игры
// «Хозяин подземелья», его отголоски, стража района, материалы.
//
// ДОГОВОР С АГЕНТОМ «МИР» (`f15.ts`, меняет только сводящий):
//   • экспорт — F15_HEART_AREA, F15_BOSS, F15_BOSS_MOBS, F15_BOSS_MATS,
//     F15_BOSS_MEATS, F15_JOIN;
//   • F15_HEART_AREA — ВЕРХНИЙ район этажа (id `f15heart`): арена (`K`,
//     ворота `G`), табличка `T`, печать `S` и лестница `>`; своего лифта нет;
//   • нижний ряд его карты — пол ровно в столбцах F15_JOIN.x0…x1, остальное
//     стена; верхний ряд последнего района «Мира» — так же (стык);
//   • id — с приставкой `f15b_` или `f15boss`; босс — `f15boss`, трофей —
//     материал `f15mat` (`stack: 1`);
//   • правила этажа (`registerFloor(15)`) — только у «Мира»; здесь — только
//     сценарий босса (`f15-boss-brains.ts`), ИИ своих монстров и рисунок
//     (`f15-boss-art.ts`, `f15-boss-fx.ts`).
//
// ============================================================================
// ДИЗАЙН-ДОКУМЕНТ «ЯДРА»
// ============================================================================
//
// Мир. На дне подземелья лежит упавшая звезда. Её свет кристаллизовал
// породу; кристаллы рождают монстров и хранят память обо всём, что было
// выше. Хозяин подземелья — не зверь и не плоть: это астральный владыка,
// дух звезды, который сам вырастил подземелье и посадил в него всех боссов.
//
// Глагол этажа — ГРАВИТАЦИЯ (растёт у «Мира» по районам: колодцы →
// телескоп и свет → орбиты и невесомость). В «Ядре» глагол доходит до
// вершины: владыка гнёт тяготение РУКАМИ — сжал кулак — колодец, развёл
// ладони — волна отталкивания, провёл рукой — планеты короны идут по
// орбите и бьют дугой. Колодцы тянут героя и снаряды так же, как в мире.
//
// Район «Ядро» (снизу вверх, карта — `scripts/dungeon/f15_boss.py`):
//   • Кристальные арки — от стыка: пары кристальных столбов, звёздная пыль.
//   • Перекрёсток лучей — развилка: прямо — к Залу памяти; налево — Жила
//     (тайник за треснувшей стеной, решётка в Зал — открывается из зала,
//     короткий путь назад); направо — Грот жеод (жеоды бьются, из пор
//     вылетают осколки звезды) и второй вход в Зал.
//   • Зал памяти — мраморный зал, колоннады, световая дорожка к воротам. В
//     северной стене шесть ниш: корона Крысиного короля, секира Минотавра,
//     череп Красного змея, голова гидры, меч Короля демонов — каждая в
//     кристалле, — и шестая, пустая. Она ждёт героя (после победы в ней
//     горит «Сердце звезды»). Подходишь — реликвия вспыхивает и шепчет
//     (зал-событие светом). Спят два Хранителя памяти.
//   • Арена — круглый зал R=13 вокруг упавшей звезды. Пол — звёздная карта:
//     золотые кольца астролябии с рисками, меридианы, созвездия; по краю —
//     восемь стоек армиллярной сферы с кольцами; в четвертях — спящие знаки
//     памяти; за звездой — печать и Колыбель с лестницей вниз.
//
// Монстры района:
//   • Осколок звезды (`f15b_shard`) — летучий кристалл: целится лучом и
//     бьёт тараном по прямой, промахнулся — звенит о стену и висит. Из пор
//     Грота и арок; в «СВЕРХНОВОЙ» его выбрасывает сама звезда.
//   • Хранитель памяти (`f15b_keeper`) — кристальный рыцарь-статуя Зала:
//     спит, встаёт на шаги, бьёт посохом кольцом по полу, медленный и
//     тяжёлый; распадается на кристаллы.
//   • Пять отголосков прошлых боссов — части боя (пролог).
//
// Босс «Хозяин подземелья» (`f15boss`) — астральный владыка: высокая
// парящая фигура (3×5 клеток), плащ из ночного неба (по нему текут звёзды
// и туманности, кромка — живая граница космоса), вместо головы — корона из
// пяти кристаллов-планет на орбитах вокруг светящегося ядра-лица, глаза —
// две звезды. Ног нет: парит (тень на полу, покачивание, шлейф плаща).
// ВСЕГДА повёрнут туда, куда летит или бьёт: разворот плавный (не больше
// `LORD.turn` рад/с), плащ отстаёт инерцией; нужно к герою — сперва
// поворачивается, потом скользит. Лист «во все стороны» — 32 румба.
//
// Фазы (засечки полосы `LORD.hp`, у каждой — вход камерой E9, свой приём,
// новый вид арены и слабое место, видное глазом):
//   0 ОТГОЛОСКИ — владыка спит, завёрнутый в плащ над звездой; неуязвим.
//     Из складок плаща по очереди выходят созвездия пяти прошлых боссов —
//     Крысиный король, Минотавр, Красный змей, Гидра, Король демонов, — у
//     каждого коронный приём. Павшее эхо зажигает звезду на плаще.
//   1 ПРОБУЖДЕНИЕ — плащ распахивается, планеты выходят на орбиты, глаза
//     зажигаются. Ладонь сверху (круг перед ним), взмах наотмашь (конус),
//     волна отталкивания (кольца друг за другом — проскочи рывком).
//     Слабое место: после удара ладонь гаснет, он открыт.
//   2 ГРАВИТАЦИЯ — сжал кулак: колодец тянет героя и снаряды, в конце
//     схлопывается; провёл рукой — планеты срываются с орбит и бьют по
//     дуге, потом возвращаются (пока их нет — ядро-лицо открыто, ×1,6;
//     корона на месте — ×0,6); звездопад кольцом метеоров. Арена:
//     сетка пола гнётся к колодцам, кольца стоек крутятся.
//   3 ПОДЗЕМЕЛЬЕ ПОМНИТ — четверти арены переписываются под прошлые этажи
//     кристаллом и звёздным светом: лава в кристальных трещинах, бездна
//     без звёзд, зеркальные кристаллы, парные круги гидры; у каждой своя
//     беда. Владыка дирижирует памятью и бьёт волной.
//   4 ЗАТМЕНИЕ — запахивает плащ: свет арены гаснет, видны только звёзды
//     плаща и его глаза. Он исчезает во тьме и бьёт из неё: перед ударом
//     звёзды вспыхивают там, куда придёт удар (честное предупреждение).
//     Окно — когда плащ распахивается (свет изнутри, ×1,6); запахнутый —
//     ×0,15, удары отскакивают со звоном.
//   5 СВЕРХНОВАЯ — плащ сгорает, корона рушится в звезду, владыка
//     становится чистым светом и сливается со звездой: лучи вращаются по
//     арене (просвет — между ними), пульсы-кольца с разрывом, звезда
//     выбрасывает осколки. После пульса свет «выдыхает» — ядро тускнеет,
//     ×1,5. Последний удар — замедление (E10) и `finale` вместе с победой.
//
// Палитра: глубокий индиго и фиолет (`#0c0820`…`#3a2a7a`), холодный
// голубой кристалл (`#5ad8ff`, `#c8f4ff`), золото звёзд (`#ffd76a`,
// `#fff2c0`); тёплое — только искры и лава памяти.
//
// Снимок для витрины: фаза ГРАВИТАЦИЯ, камера сверху на арену. В центре —
// упавшая звезда в кратере, вокруг неё золотые кольца звёздной карты; над
// ней парит владыка в распахнутом плаще-небе, корона планет кружит вокруг
// сияющего лица, одна рука сжата в кулак, и у героя под ногами
// закручивается колодец — сетка пола гнётся воронкой, а три планеты летят
// к нему дугами с золотыми следами. По краю — армиллярные кольца.

