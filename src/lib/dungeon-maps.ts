// Карты подземелья. С v2.81 у каждого этажа свой файл карт
// (`dungeon-floors/fN-map.ts`), собранный скриптом `scripts/dungeon/fN.py`
// на кистях `scripts/dungeon/brush.py`. Карты первого этажа — Вход в шахты
// и Прогрызенные штреки — лежат в `dungeon-floors/f1-map.ts`; здесь они
// только переизданы под прежними именами, чтобы старые импорты не
// разъехались. Руками карты не правят: `python3 scripts/dungeon/f1.py --write`.
//
// Базовая легенда (читает `dungeon-world.ts`):
//   #  порода                 .  пол района          ~  лужа
//   ,  пол другого вида: во Входе — грунт природных пустот, в Штреках —
//      плиты выложенных залов
//   !  рельсы вдоль (верт.)   =  рельсы поперёк      c  вагонетка на рельсах
//   C  ящик                   B  бочка               X  бочка с порохом
//   n  гнездо                 v  перевёрнутая вагонетка с гнездом
//   o  нора в стене           P  стойка крепи (не ломается)
//   L  лампа на стене         l  фонарь (горит)      u  фонарь (погашен)
//   %  треснувшая стена       $  тайник              b  доска объявлений
//   E  лифт (центр площадки)  M  вход в подземную шахту
//   G  ворота арены           K  место босса         T  табличка
//   D  решётка (открывается только с одной стороны)
//   Y  завал (дальше — следующие районы)
//   S  печать: закрыта, пока босс этажа не побеждён   >  лестница на этаж ниже
//   a  засада: трещины в своде                        R  спящая стая
//
// Свои буквы этажа 1 (ловушки, кости, нечистоты, факелы, тотемы, трон, Зал
// черепов) — `LEGEND` в `dungeon-floors/f1.ts`.

