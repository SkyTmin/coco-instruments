// Карты подземелья — нарисованы руками, символ за клеткой. Мир постоянный:
// одна и та же планировка при каждом спуске, её можно выучить. Меняются
// только мобы, ящики и лут. Каждый район — свой прямоугольник 40 клеток в
// ширину; сверху — глубже. Нижний ряд района стыкуется с верхним рядом
// следующего без швов: проход в тех же столбцах.
//
// Легенда (читает `dungeon-world.ts`):
//   #  порода                 .  пол                 ~  лужа
//   !  рельсы вдоль (верт.)   =  рельсы поперёк      c  вагонетка на рельсах
//   C  ящик                   B  бочка               X  бочка с порохом
//   n  гнездо                 v  перевёрнутая вагонетка с гнездом
//   o  нора в стене           P  стойка крепи (не ломается)
//   L  лампа на стене         l  фонарь (горит)      u  фонарь (погашен)
//   %  треснувшая стена       $  тайник              b  доска объявлений
//   E  клеть (центр площадки) M  вход в подземную шахту
//   G  ворота арены           K  место босса         T  табличка
//   D  решётка (открывается только с одной стороны)
//   Y  завал (дальше — следующие районы)
//   a  засада: трещины в своде                        R  спящая стая
//
// Карты собраны скриптом-кистью (прямоугольники, овалы, дрожь стен) и
// потом доведены руками: лампы висят только на стенах с полом под ними,
// у каждой норы есть выход на пол, ходок изолирован до решётки. Правите
// карту — прогоните `dungeon-world.test.ts`: он проверяет всё это.

