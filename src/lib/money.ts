// Как выглядит сумма на счётчике.
//
// Здесь была попытка сделать счётчик механическим — колесо с цифрами 0…9 на
// каждый разряд. На бумаге красиво, в игре — мусор, и по двум причинам сразу.
// Во-первых, при непрерывном ходе колеса в любой момент видно ПОЛОВИНКУ
// цифры: на 62 пикселях это читается как механика, на восемнадцати — как
// рваный текст. Во-вторых, каждому колесу нужен свой `overflow: hidden`, а он
// обрезает и свечение — вокруг каждой цифры появлялась своя светящаяся
// прямоугольная коробка, и число рассыпалось на разноцветные плитки.
//
// Вывод, который стоит помнить: сочность счёта делает ТЕМП, а не форма цифр.
// Темп живёт в lib/rollup.ts; цифрам достаточно быть крупными, целыми и
// хорошо читаемыми на любом кадре.

/** Неразрывный пробел: разряды не должны разъезжаться по разным строкам. */
const NBSP = ' ';

/** Сумма для счётчика: целые монеты, разряды по три. */
export function moneyText(value: number): string {
  const v = Math.max(0, Math.round(value));
  const digits = String(v);
  let out = '';
  for (let i = 0; i < digits.length; i++) {
    // Разделитель ставим перед каждой третьей цифрой с конца, кроме начала.
    if (i > 0 && (digits.length - i) % 3 === 0) out += NBSP;
    out += digits[i];
  }
  return out;
}

/** Сколько цифр в сумме. Прибавился разряд — счётчик толкает сам себя. */
export function digitCount(value: number): number {
  return String(Math.max(0, Math.round(value))).length;
}
