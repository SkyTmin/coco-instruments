// Редкость сфер-множителей.
//
// Номиналы сфер (ORB_TABLE в scatter.ts) уже расходятся на порядок по весу:
// ×2 выпадает в трёхстах случаях из тысячи, ×500 — в одном. То есть лестница
// редкости в игре была всегда — её просто не было видно: и ×2, и ×500
// рисовались одинаковым золотым шариком. Этот модуль даёт номиналу имя, цвет
// и «вес события», а всё остальное — CSS, звук и вибрация — пляшет от него.
//
// Границы тиров выбраны не на глаз, а по таблице весов: каждый следующий тир
// примерно втрое-вчетверо реже предыдущего (66 / 22 / 9 / 2,2 / 0,6 / 0,2 %).
// Проценты считаются из тех же весов в orb-rarity.test.ts — если таблицу
// номиналов однажды поправят, тест уронит расхождение, а не пользователь.

export type OrbRarity = 'common' | 'uncommon' | 'rare' | 'epic' | 'legendary' | 'mythic';

export interface OrbTier {
  id: OrbRarity;
  /** Название для правил и для плашки над сферой. */
  name: string;
  /** Наименьший номинал, попадающий в этот тир. */
  min: number;
  /** Доля сфер этого тира среди всех, в процентах. */
  chance: number;
  /**
   * Сколько «тактов» празднования заслуживает находка: 0 — сфера просто
   * падает, 1 — короткий блик, 2 — вспышка и пауза, 3 — полноэкранный показ.
   * Психология тут простая: если легендарная сфера показывается тем же
   * способом, что и обычная, она перестаёт быть легендарной.
   */
  beats: 0 | 1 | 2 | 3;
}

/**
 * От частого к редкому. Порядок важен: `orbRarity` идёт с конца и берёт
 * первый тир, чей `min` не выше номинала.
 */
export const ORB_TIERS: OrbTier[] = [
  { id: 'common', name: 'Обычная', min: 2, chance: 66, beats: 0 },
  // «Добротная», а не «Необычная»: второе — это первое с приставкой «не-»,
  // то есть отрицание, а не своя ступень. «Добротная» — сделана на совесть.
  { id: 'uncommon', name: 'Добротная', min: 5, chance: 22, beats: 0 },
  { id: 'rare', name: 'Редкая', min: 10, chance: 9, beats: 1 },
  // «Заветная» вместо стёртого «Эпическая»: это про желание, а не про размер.
  { id: 'epic', name: 'Заветная', min: 20, chance: 2.2, beats: 2 },
  { id: 'legendary', name: 'Легендарная', min: 50, chance: 0.6, beats: 3 },
  // Верхняя ступень нарочно ломает грамматику лестницы: не прилагательное,
  // а существительное. Одно это уже говорит «у меня правила другие».
  { id: 'mythic', name: 'Реликвия', min: 250, chance: 0.2, beats: 3 },
];

const BY_ID = new Map(ORB_TIERS.map((t) => [t.id, t]));

/** Тир номинала сферы. Ниже ×2 сфер не бывает, но на всякий случай — обычная. */
export function orbRarity(value: number): OrbRarity {
  for (let i = ORB_TIERS.length - 1; i >= 0; i--) {
    if (value >= ORB_TIERS[i].min) return ORB_TIERS[i].id;
  }
  return 'common';
}

export function orbTier(value: number): OrbTier {
  return BY_ID.get(orbRarity(value)) ?? ORB_TIERS[0];
}

/**
 * Тир накопленной суммы множителей. Сумма — это то, что реально умножает
 * выплату, поэтому и празднуется она по той же лестнице: три обычные сферы
 * по ×4 в сумме дают ×12, и это честно «редкий» момент, а не три скучных.
 */
export function multRarity(sum: number): OrbRarity {
  return orbRarity(sum);
}

/** Насколько «громко» показывать находку: максимум из тиров всех сфер звена. */
export function loudestTier(values: number[]): OrbTier {
  return values.reduce<OrbTier>(
    (best, v) => (orbTier(v).beats > best.beats ? orbTier(v) : best),
    ORB_TIERS[0],
  );
}
