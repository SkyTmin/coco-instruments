// Арифметика механического счётчика: на сколько повёрнуто колесо разряда.
//
// Живёт отдельно от компонента, потому что здесь легко ошибиться незаметно:
// колесо, повёрнутое не туда, показывает половинку цифры — и счётчик
// читается как сломанный, а не как механический. Такое ловится тестом,
// а на глаз — нет.

/**
 * Окно подхвата для разряда `p`: последняя его 10^-p доля.
 *
 * Это не подгонка, а устройство настоящего счётчика. Десятки поворачиваются,
 * пока единицы идут с девятки на ноль, — то есть последнюю ДЕСЯТУЮ своего
 * разряда. Сотни поворачиваются, пока с девятки на ноль идут десятки, а это
 * уже последняя СОТАЯ их разряда. И так далее: окно сужается вдесятеро на
 * каждый разряд, поэтому старшие колёса стоят намертво и щёлкают только в
 * общий перевал.
 *
 * Одно окно на все разряды (я сперва так и сделал) даёт вот что: на
 * 49 999 006 старший разряд оказывается на 99,9% пути и показывает половину
 * четвёрки с половиной пятёрки. Ни одного неверного числа на экране нет — и
 * всё равно выглядит поломкой.
 */
export const catchWindow = (place: number): number => Math.pow(0.1, place);

/**
 * Положение колеса разряда `place` для показания `value`, в цифрах: 3.0 —
 * колесо ровно на тройке, 3.5 — ровно между тройкой и четвёркой. Диапазон
 * [0, 10): на десятке колесо замыкается обратно на ноль.
 */
export function wheelPos(value: number, place: number): number {
  const v = Math.max(0, value);
  const p10 = 10 ** place;
  const whole = Math.floor(v / p10);
  const frac = (v - whole * p10) / p10;
  // Младший разряд крутится непрерывно — он и есть ход счётчика.
  const w = catchWindow(place);
  const roll = place === 0 ? frac : Math.max(0, frac - (1 - w)) / w;
  return (whole % 10) + roll;
}

/** Сколько разрядов занимает показание (с учётом обязательного минимума). */
export function wheelCount(value: number, min = 1): number {
  return Math.max(min, String(Math.floor(Math.max(0, value))).length);
}

/**
 * Виден ли разделитель разрядов, стоящий ПОСЛЕ разряда `place`. Виден только
 * тогда, когда за ним есть цифры: «999», а не «␠999».
 */
export function sepVisible(place: number, len: number): boolean {
  return place < len;
}
