// ---------------------------------------------------------------------------
// Кирки (v2.67) — как в Майнкрафте и Terraria: кирка куётся ИЗ руды своего
// этажа и открывает следующие этажи. Железной киркой берётся кобальт,
// бирюзовой — янтарь. У кирки две цифры для игрока: Сила ⛏ (руду какой
// твёрдости она берёт) и Скорость (блоков в минуту). Урон — внутреннее
// число, в интерфейсе его нет; заточки нет совсем.
//
// Выковка без заказа: руда для следующей кирки сама откладывается в ящик
// кузнеца, когда продаёшь рюкзак, и кирка куётся одной кнопкой, как только
// хватает руды и монет. Три последние — из руды спецзоны, после престижа.
// ---------------------------------------------------------------------------

export interface PickDef {
  id: string;
  name: string;
  /** Сила ⛏: руду какой твёрдости берёт (см. `rockHardness`). */
  power: number;
  /** Урон за удар — ВНУТРЕННЕЕ число: игрок видит скорость, а не урон. */
  dmg: number;
  /** Ударов в секунду на удержании. */
  rate: number;
  /** С какого этажа куётся: этаж руды-материала. */
  floor: number;
  /** С какого престижа (для кирок спецзоны). */
  prestige: number;
  coins: number;
  /** Руда: [порода, сколько]. Первая — материал, вторая — старая руда. */
  ore: [number, number][];
  /** Цвет головки — для иконки. */
  head: string;
  /** Редкость 0…6 (`lib/rarity.ts`): чем выше, тем ярче кирка. */
  rarity: number;
}

