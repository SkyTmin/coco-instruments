/** Заточка на КАЖДОЙ кирке: +0…+10, +3,5% урона за уровень. */
export const SHARP_MAX = 10;
export const SHARP_STEP = 0.035;

/** Цена следующего уровня заточки кирки `pick` (с уровня `level`). */
export function sharpCost(pick: number, level: number): number {
  const p = PICKS[Math.max(0, Math.min(PICKS.length - 1, pick))];
  if (!p.coins) return nice(10 * Math.pow(1.3, level));
  return nice(p.coins * 0.03 * (1 + 0.3 * level));
}

/** Две значащие цифры: цена «1 800», а не «1 793». */
export function nice(x: number): number {
  if (x < 100) return Math.round(x);
  const p = Math.pow(10, Math.floor(Math.log10(x)) - 1);
  return Math.round(x / p) * p;
}
